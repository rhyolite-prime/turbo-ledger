Json::Value termJson(const m::DepositAccountTermAndPreclosure &r) {
    Json::Value j;
    j["id"] = r.getValueOfId();
    if (r.getDepositAmount()) j["depositAmount"] = moneyJson(r.getValueOfDepositAmount());
    if (r.getDepositPeriod()) j["depositPeriod"] = r.getValueOfDepositPeriod();
    if (r.getDepositPeriodFrequencyType()) j["depositPeriodFrequencyType"] = r.getValueOfDepositPeriodFrequencyType();
    if (r.getMaturityAmount()) j["maturityAmount"] = moneyJson(r.getValueOfMaturityAmount());
    if (r.getMaturityDate()) j["maturityDate"] = dateStr(r.getValueOfMaturityDate());
    if (r.getExpectedFirstdepositOnDate())
        j["expectedFirstDepositOnDate"] = dateStr(r.getValueOfExpectedFirstdepositOnDate());
    j["isRenewalAllowed"] = r.getValueOfIsRenewalAllowed();
    j["isPrematureClosureAllowed"] = r.getValueOfIsPrematureClosureAllowed();
    j["preClosurePenalApplicable"] = r.getValueOfPreClosurePenalApplicable();
    if (r.getPreClosurePenalInterest()) j["preClosurePenalInterest"] = moneyJson(r.getValueOfPreClosurePenalInterest());
    if (r.getOnAccountClosureType()) j["onAccountClosureType"] = r.getValueOfOnAccountClosureType();
    if (r.getTransferToSavingsAccountId()) j["transferToSavingsAccountId"] = r.getValueOfTransferToSavingsAccountId();
    return j;
}
int balanceDeltaSign(int transactionType) {
    switch (transactionType) {
        case kTxnDeposit:
        case kTxnInterestPosting:
        case kTxnTransferIn:
            return 1;
        case kTxnWithdrawal:
        case kTxnWithdrawalFee:
        case kTxnAnnualFee:
        case kTxnFeeCharge:
        case kTxnPenaltyCharge:
        case kTxnOverdraftInterest:
        case kTxnTransferOut:
            return -1;
        default:
            return 0;  // hold/release don't move the ledger balance
    }
}
