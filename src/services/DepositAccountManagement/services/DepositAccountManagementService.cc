drogon::Task<Json::Value> DepositAccountManagementService::createAccountTransaction(
    const turbo::RequestContext &ctx, std::string accountId, std::string command, Json::Value body) {
    requirePermission(ctx, "CREATE_SAVINGSACCOUNTTRANSACTION");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    m::SavingsAccount account;
    try {
        account = co_await Mapper<m::SavingsAccount>(txn).findByPrimaryKey(accountId);
    } catch (const UnexpectedRows &) {
        throw ApiError(drogon::k404NotFound, "Savings account not found", "error.msg.savingsaccount.not.found");
    }
    if (account.getValueOfStatus() != kStatusActive)
        throw ApiError(drogon::k409Conflict, "Account must be active to post transactions",
                       "error.msg.savingsaccount.not.active");
    const auto amount = moneyOr(body, "transactionAmount", moneyOr(body, "amount"));
    if (amount.isZero() || amount.isNegative())
        throw ApiError(drogon::k400BadRequest, "A positive transactionAmount is required",
                       "error.msg.savingsaccounttransaction.amount.invalid");
    const auto txDate = asStringOr(body, "transactionDate", dateStr(Date::now()));

    int transactionType;
    if (command == "deposit") {
        if (account.getValueOfIsCreditBlocked())
            throw ApiError(drogon::k409Conflict, "Credits are blocked for this account",
                           "error.msg.savingsaccount.credit.blocked");
        transactionType = kTxnDeposit;
    } else if (command == "withdrawal") {
        if (account.getValueOfIsDebitBlocked())
            throw ApiError(drogon::k409Conflict, "Debits are blocked for this account",
                           "error.msg.savingsaccount.debit.blocked");
        const auto balance = turbo::Money::parse(account.getValueOfAccountBalanceDerived()).value_or(turbo::Money());
        const auto overdraftLimit = account.getOverdraftLimit()
                                        ? turbo::Money::parse(account.getValueOfOverdraftLimit()).value_or(turbo::Money())
                                        : turbo::Money();
        const auto minRequired = account.getMinRequiredBalance()
                                     ? turbo::Money::parse(account.getValueOfMinRequiredBalance()).value_or(turbo::Money())
                                     : turbo::Money();
        const auto floor = account.getValueOfAllowOverdraft() ? -overdraftLimit : minRequired;
        if ((balance - amount).micros() < floor.micros())
            throw ApiError(drogon::k400BadRequest, "Insufficient funds for this withdrawal",
                           "error.msg.savingsaccounttransaction.insufficient.funds");
        transactionType = kTxnWithdrawal;
    } else {
        throw ApiError(drogon::k400BadRequest, "Unknown transaction command: " + command,
                       "error.msg.savingsaccounttransaction.unknown.command");
    }

    const auto txId = co_await postTransaction(txn, ctx, accountId, transactionType, txDate,
                                               amount.toString(false), asStringOr(body, "description"));

    if (command == "withdrawal" && account.getValueOfWithdrawalFeeForTransfer()) {
        // Withdrawal-fee charges attached to the account (charge_time_type =
        // kChargeTimeWithdrawalFee) are billed alongside the withdrawal.
        auto fees = co_await Mapper<m::SavingsAccountCharge>(txn).findBy(
            Criteria(m::SavingsAccountCharge::Cols::_savings_account_id, accountId) &&
            Criteria(m::SavingsAccountCharge::Cols::_charge_time_type, kChargeTimeWithdrawalFee) &&
            Criteria(m::SavingsAccountCharge::Cols::_is_active, true));
        for (auto &fee : fees) {
            const auto outstanding = turbo::Money::parse(fee.getValueOfAmountOutstandingDerived()).value_or(turbo::Money());
            if (outstanding.isZero()) continue;
            co_await postTransaction(txn, ctx, accountId, kTxnWithdrawalFee, txDate,
                                     outstanding.toString(false), "Withdrawal fee");
            fee.setAmountPaidDerived(outstanding.toString(false));
            fee.setAmountOutstandingDerived("0");
            fee.setIsPaidDerived(true);
            co_await Mapper<m::SavingsAccountCharge>(txn).update(fee);
        }
    }
    co_return co_await transactionToJson(txn, txId);
}

drogon::Task<Json::Value> DepositAccountManagementService::handleAccountTransactionCommand(
    const turbo::RequestContext &ctx, std::string accountId, std::string transactionId, std::string command,
    Json::Value body) {
    requirePermission(ctx, "UPDATE_SAVINGSACCOUNTTRANSACTION");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    Mapper<m::SavingsAccountTransaction> mapper(txn);
    m::SavingsAccountTransaction row;
    try {
        row = co_await mapper.findByPrimaryKey(transactionId);
    } catch (const UnexpectedRows &) {
        throw ApiError(drogon::k404NotFound, "Savings account transaction not found",
                       "error.msg.savingsaccounttransaction.not.found");
    }
    if (row.getValueOfSavingsAccountId() != accountId)
        throw ApiError(drogon::k404NotFound, "Savings account transaction not found",
                       "error.msg.savingsaccounttransaction.not.found");

    if (command == "undo" || command == "reverse") {
        if (row.getValueOfIsReversed())
            throw ApiError(drogon::k409Conflict, "Transaction is already reversed",
                           "error.msg.savingsaccounttransaction.already.reversed");
        row.setIsReversed(true);
        co_await mapper.update(row);
        // Post the exact inverse so the running-balance chain stays correct
        // without needing to rewrite subsequent transactions' balances.
        const int originalSign = balanceDeltaSign(row.getValueOfTransactionType());
        if (originalSign != 0) {
            const int inverseType = originalSign > 0 ? kTxnWithdrawal : kTxnDeposit;
            co_await postTransaction(txn, ctx, accountId, inverseType, dateStr(Date::now()),
                                     row.getValueOfAmount(), "Reversal of transaction " + transactionId);
        }
    } else if (command == "releaseAmount") {
        if (!row.getValueOfIsHoldTransaction())
            throw ApiError(drogon::k400BadRequest, "Transaction is not a hold", "error.msg.savingsaccounttransaction.not.hold");
        m::SavingsAccountTransaction release;
        release.setSavingsAccountId(accountId);
        release.setTransactionType(kTxnAmountRelease);
        release.setTransactionDate(Date::now());
        release.setAmount(row.getValueOfAmount());
        auto account = co_await Mapper<m::SavingsAccount>(txn).findByPrimaryKey(accountId);
        release.setRunningBalanceDerived(account.getValueOfAccountBalanceDerived());
        release.setIsReversed(false);
        release.setIsHoldTransaction(false);
        release.setReleaseIdOfHold(transactionId);
        release.setSubmittedOnDate(Date::now());
        release.setCreatedBy(userIdOr(ctx));
        release.setUpdatedBy(userIdOr(ctx));
        co_await Mapper<m::SavingsAccountTransaction>(txn).insert(release);
    } else if (command == "modify" || command == "adjust") {
        if (row.getValueOfIsReversed())
            throw ApiError(drogon::k409Conflict, "Transaction is already reversed",
                           "error.msg.savingsaccounttransaction.already.reversed");
        row.setIsReversed(true);
        co_await mapper.update(row);
        const int originalSign = balanceDeltaSign(row.getValueOfTransactionType());
        if (originalSign != 0) {
            const int inverseType = originalSign > 0 ? kTxnWithdrawal : kTxnDeposit;
            co_await postTransaction(txn, ctx, accountId, inverseType, dateStr(Date::now()),
                                     row.getValueOfAmount(), "Reversal prior to modify " + transactionId);
        }
        const auto newAmount = moneyOr(body, "transactionAmount", moneyOr(body, "amount"));
        const auto newDate = asStringOr(body, "transactionDate", dateStr(row.getValueOfTransactionDate()));
        co_await postTransaction(txn, ctx, accountId, row.getValueOfTransactionType(), newDate,
                                 newAmount.toString(false), "Modified replacement of " + transactionId);
    } else {
        throw ApiError(drogon::k400BadRequest, "Unknown command: " + command,
                       "error.msg.savingsaccounttransaction.unknown.command");
    }
    co_await turbo::outbox::writeEvent(txn, ctx, "savingsaccounttransaction", transactionId,
                                       "savingsaccounttransaction." + command, body);
    co_return co_await listAccountTransactions(ctx, accountId);
}

