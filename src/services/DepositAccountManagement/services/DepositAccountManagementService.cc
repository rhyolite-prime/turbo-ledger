drogon::Task<Json::Value> DepositAccountManagementService::listStandingInstructionHistory(
    const turbo::RequestContext &ctx, const std::string &clientId) {
    requirePermission(ctx, "READ_STANDINGINSTRUCTION");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    std::vector<std::string> siIds;
    if (!clientId.empty()) {
        auto siRows = co_await Mapper<m::StandingInstruction>(txn).findBy(
            Criteria(m::StandingInstruction::Cols::_client_id, clientId));
        for (const auto &s : siRows) siIds.push_back(s.getValueOfId());
    }
    Mapper<m::StandingInstructionHistory> mapper(txn);
    mapper.orderBy(m::StandingInstructionHistory::Cols::_execution_date, SortOrder::DESC);
    Json::Value items(Json::arrayValue);
    if (clientId.empty()) {
        auto rows = co_await mapper.findAll();
        for (const auto &r : rows) items.append(siHistoryJson(r));
    } else {
        for (const auto &id : siIds) {
            auto rows = co_await Mapper<m::StandingInstructionHistory>(txn).findBy(
                Criteria(m::StandingInstructionHistory::Cols::_standing_instruction_id, id));
            for (const auto &r : rows) items.append(siHistoryJson(r));
        }
    }
    co_return items;
}

