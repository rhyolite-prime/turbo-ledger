drogon::Task<Json::Value> DepositAccountManagementService::createAccount(const turbo::RequestContext &ctx,
                                                                         int depositType, Json::Value body) {
    requirePermission(ctx, depositTypeAccountPermission("CREATE", depositType));
    const auto productId = asStringOr(body, "productId");
    const auto clientId = asStringOr(body, "clientId");
    if (productId.empty())
        throw ApiError(drogon::k400BadRequest, "productId is required", "error.msg.savingsaccount.product.required");
    if (clientId.empty() && asStringOr(body, "groupId").empty())
        throw ApiError(drogon::k400BadRequest, "clientId or groupId is required",
                       "error.msg.savingsaccount.owner.required");

    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    m::SavingsProduct product;
    try {
        product = co_await Mapper<m::SavingsProduct>(txn).findByPrimaryKey(productId);
    } catch (const UnexpectedRows &) {
        throw ApiError(drogon::k404NotFound, "Product not found", "error.msg.savingsproduct.not.found");
    }
    if (product.getValueOfDepositType() != depositType)
        throw ApiError(drogon::k400BadRequest, "productId does not match account type",
                       "error.msg.savingsaccount.product.mismatch");

    m::SavingsAccount row;
    row.setDepositType(depositType);
    if (!clientId.empty()) row.setClientId(clientId);
    if (body.isMember("groupId") && !asStringOr(body, "groupId").empty()) row.setGroupId(asStringOr(body, "groupId"));
    row.setProductId(productId);
    if (body.isMember("fieldOfficerId") && !asStringOr(body, "fieldOfficerId").empty())
        row.setFieldOfficerId(asStringOr(body, "fieldOfficerId"));
    row.setStatus(kStatusSubmittedAndPendingApproval);
    row.setSubStatus(kSubStatusNone);
    row.setAccountType(asIntOr(body, "accountType", 1));
    row.setCurrencyCode(product.getValueOfCurrencyCode());
    row.setDigitsAfterDecimal(product.getValueOfDigitsAfterDecimal());
    row.setInMultiplesOf(product.getValueOfInMultiplesOf());
    row.setNominalAnnualInterestRate(asStringOr(body, "nominalAnnualInterestRate",
                                                product.getValueOfNominalAnnualInterestRate()));
    row.setInterestCompoundingPeriodType(product.getValueOfInterestCompoundingPeriodType());
    row.setInterestPostingPeriodType(product.getValueOfInterestPostingPeriodType());
    row.setInterestCalculationType(product.getValueOfInterestCalculationType());
    row.setInterestCalculationDaysInYearType(product.getValueOfInterestCalculationDaysInYearType());
    if (product.getMinRequiredOpeningBalance())
        row.setMinRequiredOpeningBalance(product.getValueOfMinRequiredOpeningBalance());
    if (product.getLockinPeriodFrequency()) row.setLockinPeriodFrequency(product.getValueOfLockinPeriodFrequency());
    if (product.getLockinPeriodFrequencyType())
        row.setLockinPeriodFrequencyType(product.getValueOfLockinPeriodFrequencyType());
    row.setWithdrawalFeeForTransfer(product.getValueOfWithdrawalFeeForTransfer());
    row.setAllowOverdraft(asBoolOr(body, "allowOverdraft", product.getValueOfAllowOverdraft()));
    if (product.getOverdraftLimit()) row.setOverdraftLimit(product.getValueOfOverdraftLimit());
    if (product.getMinBalanceForInterestCalculation())
        row.setMinBalanceForInterestCalculation(product.getValueOfMinBalanceForInterestCalculation());
    if (product.getMinRequiredBalance()) row.setMinRequiredBalance(product.getValueOfMinRequiredBalance());
    row.setEnforceMinRequiredBalance(product.getValueOfEnforceMinRequiredBalance());
    row.setSubmittedOnDate(dateOr(asStringOr(body, "submittedOnDate"), Date::now()));
    row.setSubmittedBy(userIdOr(ctx));
    row.setAccountBalanceDerived("0");
    row.setTotalDepositsDerived("0");
    row.setTotalWithdrawalsDerived("0");
    row.setTotalInterestPostedDerived("0");
    row.setTotalFeeChargeDerived("0");
    row.setTotalWithdrawalFeeDerived("0");
    row.setIsCreditBlocked(false);
    row.setIsDebitBlocked(false);
    row.setIsInterestBlocked(false);
    row.setIsGsimParent(false);
    row.setExternalId(asStringOr(body, "externalId", turbo::ids::newUuid()));
    row.setCreatedBy(userIdOr(ctx));
    row.setUpdatedBy(userIdOr(ctx));

    row = co_await Mapper<m::SavingsAccount>(txn).insert(row);
    row.setAccountNo(co_await generateAccountNumber(txn, depositType, row.getValueOfId()));
    co_await Mapper<m::SavingsAccount>(txn).update(row);

    if (depositType != kDepositTypeSavings) {
        m::DepositAccountTermAndPreclosure term;
        term.setSavingsAccountId(row.getValueOfId());
        if (body.isMember("depositAmount")) term.setDepositAmount(moneyOr(body, "depositAmount").toString(false));
        term.setDepositPeriod(asIntOr(body, "depositPeriod", product.getValueOfMinDepositTerm()));
        term.setDepositPeriodFrequencyType(asIntOr(body, "depositPeriodFrequencyType",
                                                   product.getValueOfMinDepositTermType()
                                                       ? product.getValueOfMinDepositTermType()
                                                       : 2));
        if (depositType == kDepositTypeRecurringDeposit)
            term.setExpectedFirstdepositOnDate(
                dateOr(asStringOr(body, "expectedFirstDepositOnDate"), row.getValueOfSubmittedOnDate()));
        term.setIsRenewalAllowed(asBoolOr(body, "isRenewalAllowed", false));
        term.setIsPrematureClosureAllowed(true);
        term.setPreClosurePenalApplicable(product.getPreClosurePenalApplicable()
                                              ? product.getValueOfPreClosurePenalApplicable()
                                              : false);
        if (product.getPreClosurePenalInterest()) term.setPreClosurePenalInterest(product.getValueOfPreClosurePenalInterest());
        if (product.getPreClosurePenalInterestOnType())
            term.setPreClosurePenalInterestOnType(product.getValueOfPreClosurePenalInterestOnType());
        co_await Mapper<m::DepositAccountTermAndPreclosure>(txn).insert(term);
    }

    co_await turbo::outbox::writeEvent(txn, ctx, "savingsaccount", row.getValueOfId(),
                                       "savingsaccount." + depositTypeLabel(depositType) + ".submitted",
                                       accountJson(row));
    co_return co_await accountToJson(txn, row.getValueOfId());
}

drogon::Task<Json::Value> DepositAccountManagementService::updateAccount(const turbo::RequestContext &ctx,
                                                                         int depositType, std::string id,
                                                                         Json::Value body) {
    requirePermission(ctx, depositTypeAccountPermission("UPDATE", depositType));
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    Mapper<m::SavingsAccount> mapper(txn);
    m::SavingsAccount row;
    try {
        row = co_await mapper.findByPrimaryKey(id);
    } catch (const UnexpectedRows &) {
        throw ApiError(drogon::k404NotFound, "Savings account not found", "error.msg.savingsaccount.not.found");
    }
    if (row.getValueOfStatus() == kStatusClosed || row.getValueOfStatus() == kStatusRejected ||
        row.getValueOfStatus() == kStatusWithdrawn || row.getValueOfStatus() == kStatusPrematureClosed)
        throw ApiError(drogon::k409Conflict, "Account is in a terminal state and cannot be modified",
                       "error.msg.savingsaccount.terminal.state");
    if (body.isMember("fieldOfficerId")) row.setFieldOfficerId(asStringOr(body, "fieldOfficerId"));
    if (body.isMember("nominalAnnualInterestRate") && row.getValueOfStatus() == kStatusSubmittedAndPendingApproval)
        row.setNominalAnnualInterestRate(moneyOr(body, "nominalAnnualInterestRate").toString(false));
    if (body.isMember("minRequiredBalance")) row.setMinRequiredBalance(moneyOr(body, "minRequiredBalance").toString(false));
    if (body.isMember("allowOverdraft")) row.setAllowOverdraft(asBoolOr(body, "allowOverdraft", false));
    if (body.isMember("overdraftLimit")) row.setOverdraftLimit(moneyOr(body, "overdraftLimit").toString(false));
    row.setUpdatedBy(userIdOr(ctx));
    co_await mapper.update(row);
    co_await turbo::outbox::writeEvent(txn, ctx, "savingsaccount", id, "savingsaccount.updated", body);
    co_return co_await accountToJson(txn, id);
}

