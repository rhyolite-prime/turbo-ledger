drogon::Task<Json::Value> DepositAccountManagementService::createStandingInstruction(
    const turbo::RequestContext &ctx, Json::Value body) {
    requirePermission(ctx, "CREATE_STANDINGINSTRUCTION");
    const auto name = asStringOr(body, "name");
    const auto fromAccountId = asStringOr(body, "fromAccountId");
    const auto toAccountId = asStringOr(body, "toAccountId");
    if (name.empty() || fromAccountId.empty() || toAccountId.empty())
        throw ApiError(drogon::k400BadRequest, "name, fromAccountId and toAccountId are required",
                       "error.msg.standinginstruction.invalid");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    m::StandingInstruction row;
    row.setName(name);
    if (body.isMember("description")) row.setDescription(asStringOr(body, "description"));
    if (!asStringOr(body, "clientId").empty()) row.setClientId(asStringOr(body, "clientId"));
    if (!asStringOr(body, "fromOfficeId").empty()) row.setFromOfficeId(asStringOr(body, "fromOfficeId"));
    if (!asStringOr(body, "fromClientId").empty()) row.setFromClientId(asStringOr(body, "fromClientId"));
    row.setFromAccountType(asIntOr(body, "fromAccountType", kTransferAccountTypeSavings));
    row.setFromAccountId(fromAccountId);
    if (!asStringOr(body, "toOfficeId").empty()) row.setToOfficeId(asStringOr(body, "toOfficeId"));
    if (!asStringOr(body, "toClientId").empty()) row.setToClientId(asStringOr(body, "toClientId"));
    row.setToAccountType(asIntOr(body, "toAccountType", kTransferAccountTypeSavings));
    row.setToAccountId(toAccountId);
    row.setInstructionType(asIntOr(body, "instructionType", 2));
    row.setStatus(kSiStatusActive);
    row.setPriority(asIntOr(body, "priority", 1));
    row.setTransferType(asIntOr(body, "transferType", 1));
    if (body.isMember("amount")) row.setAmount(moneyOr(body, "amount").toString(false));
    row.setValidFrom(dateOr(asStringOr(body, "validFrom"), Date::now()));
    if (body.isMember("validTill")) row.setValidTill(dateOr(asStringOr(body, "validTill"), Date::now()));
    row.setRecurrenceType(asIntOr(body, "recurrenceType", 1));
    if (body.isMember("recurrenceFrequency")) row.setRecurrenceFrequency(asIntOr(body, "recurrenceFrequency", 1));
    if (body.isMember("recurrenceInterval")) row.setRecurrenceInterval(asIntOr(body, "recurrenceInterval", 1));
    if (body.isMember("recurrenceOnDay")) row.setRecurrenceOnDay(asIntOr(body, "recurrenceOnDay", 1));
    row.setCreatedBy(userIdOr(ctx));
    row.setUpdatedBy(userIdOr(ctx));
    row = co_await Mapper<m::StandingInstruction>(txn).insert(row);
    co_await turbo::outbox::writeEvent(txn, ctx, "standinginstruction", row.getValueOfId(),
                                       "standinginstruction.created", siJson(row));
    co_return siJson(row);
}

drogon::Task<Json::Value> DepositAccountManagementService::updateStandingInstruction(
    const turbo::RequestContext &ctx, std::string id, Json::Value body) {
    requirePermission(ctx, "UPDATE_STANDINGINSTRUCTION");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    Mapper<m::StandingInstruction> mapper(txn);
    m::StandingInstruction row;
    try {
        row = co_await mapper.findByPrimaryKey(id);
    } catch (const UnexpectedRows &) {
        throw ApiError(drogon::k404NotFound, "Standing instruction not found",
                       "error.msg.standinginstruction.not.found");
    }
    // Fineract's own API deletes a standing instruction via PUT command=delete
    // rather than a dedicated DELETE route (see ENDPOINT_INVENTORY.md — there
    // is no DELETE row for standinginstructions); mirrored here as a status
    // flip rather than a destructive delete, so run-history stays intact.
    if (asStringOr(body, "command") == "delete" || asBoolOr(body, "delete", false)) {
        row.setStatus(kSiStatusDisabled);
        row.setUpdatedBy(userIdOr(ctx));
        co_await mapper.update(row);
        co_await turbo::outbox::writeEvent(txn, ctx, "standinginstruction", id, "standinginstruction.deleted",
                                           Json::Value());
        co_return siJson(row);
    }
    if (body.isMember("name")) row.setName(asStringOr(body, "name"));
    if (body.isMember("description")) row.setDescription(asStringOr(body, "description"));
    if (body.isMember("amount")) row.setAmount(moneyOr(body, "amount").toString(false));
    if (body.isMember("validTill")) row.setValidTill(dateOr(asStringOr(body, "validTill"), Date::now()));
    if (body.isMember("priority")) row.setPriority(asIntOr(body, "priority", 1));
    if (body.isMember("status")) row.setStatus(asIntOr(body, "status", kSiStatusActive));
    row.setUpdatedBy(userIdOr(ctx));
    co_await mapper.update(row);
    co_await turbo::outbox::writeEvent(txn, ctx, "standinginstruction", id, "standinginstruction.updated", body);
    co_return co_await standingInstructionToJson(txn, id);
}

