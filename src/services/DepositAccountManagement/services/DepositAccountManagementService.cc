drogon::Task<Json::Value> DepositAccountManagementService::listOnHoldTransactions(
    const turbo::RequestContext &ctx, std::string accountId) {
    requirePermission(ctx, "READ_SAVINGSACCOUNTTRANSACTION");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    auto holds = co_await Mapper<m::SavingsAccountTransaction>(txn).findBy(
        Criteria(m::SavingsAccountTransaction::Cols::_savings_account_id, accountId) &&
        Criteria(m::SavingsAccountTransaction::Cols::_is_hold_transaction, true));
    auto all = co_await Mapper<m::SavingsAccountTransaction>(txn).findBy(
        Criteria(m::SavingsAccountTransaction::Cols::_savings_account_id, accountId));
    std::vector<std::string> released;
    for (const auto &r : all)
        if (r.getReleaseIdOfHold()) released.push_back(r.getValueOfReleaseIdOfHold());
    Json::Value items(Json::arrayValue);
    for (const auto &r : holds) {
        if (std::find(released.begin(), released.end(), r.getValueOfId()) != released.end()) continue;
        items.append(transactionJson(r));
    }
    co_return items;
}

