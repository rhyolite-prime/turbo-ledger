drogon::Task<std::string> DepositAccountManagementService::postTransaction(
    Txn txn, const turbo::RequestContext &ctx, const std::string &accountId, int transactionType,
    const std::string &transactionDate, const std::string &amountMicros, const std::string &description) {
    Mapper<m::SavingsAccount> accMapper(txn);
    auto account = co_await accMapper.findByPrimaryKey(accountId);

    const auto amount = turbo::Money::parse(amountMicros).value_or(turbo::Money());
    const int sign = balanceDeltaSign(transactionType);
    auto currentBalance = turbo::Money::parse(account.getValueOfAccountBalanceDerived()).value_or(turbo::Money());
    const auto newBalance = sign >= 0 ? currentBalance + amount : currentBalance - amount;

    m::SavingsAccountTransaction t;
    t.setSavingsAccountId(accountId);
    t.setTransactionType(transactionType);
    t.setTransactionDate(dateOr(transactionDate, Date::now()));
    t.setAmount(amount.toString(false));
    t.setRunningBalanceDerived(newBalance.toString(false));
    t.setIsReversed(false);
    t.setIsHoldTransaction(transactionType == kTxnAmountHold);
    t.setSubmittedOnDate(Date::now());
    if (!description.empty()) t.setDescription(description);
    t.setCreatedBy(userIdOr(ctx));
    t.setUpdatedBy(userIdOr(ctx));
    t = co_await Mapper<m::SavingsAccountTransaction>(txn).insert(t);

    if (sign != 0) account.setAccountBalanceDerived(newBalance.toString(false));
    if (transactionType == kTxnDeposit) {
        auto totalDep = turbo::Money::parse(account.getValueOfTotalDepositsDerived()).value_or(turbo::Money());
        account.setTotalDepositsDerived((totalDep + amount).toString(false));
    } else if (transactionType == kTxnWithdrawal) {
        auto totalW = turbo::Money::parse(account.getValueOfTotalWithdrawalsDerived()).value_or(turbo::Money());
        account.setTotalWithdrawalsDerived((totalW + amount).toString(false));
    } else if (transactionType == kTxnInterestPosting) {
        auto totalI = turbo::Money::parse(account.getValueOfTotalInterestPostedDerived()).value_or(turbo::Money());
        account.setTotalInterestPostedDerived((totalI + amount).toString(false));
    } else if (transactionType == kTxnFeeCharge || transactionType == kTxnAnnualFee ||
              transactionType == kTxnPenaltyCharge) {
        auto totalF = turbo::Money::parse(account.getValueOfTotalFeeChargeDerived()).value_or(turbo::Money());
        account.setTotalFeeChargeDerived((totalF + amount).toString(false));
    } else if (transactionType == kTxnWithdrawalFee) {
        auto totalWF = turbo::Money::parse(account.getValueOfTotalWithdrawalFeeDerived()).value_or(turbo::Money());
        account.setTotalWithdrawalFeeDerived((totalWF + amount).toString(false));
    }
    account.setUpdatedBy(userIdOr(ctx));
    co_await accMapper.update(account);

    // GL-posting event — see header comment: no live Accounting integration
    // exists yet, so this carries everything a future consumer needs
    // (product id doubles as the GL-mapping key once that mapping exists).
    Json::Value glPayload;
    glPayload["savingsAccountId"] = accountId;
    glPayload["productId"] = account.getValueOfProductId();
    glPayload["transactionId"] = t.getValueOfId();
    glPayload["transactionType"] = transactionType;
    glPayload["transactionDate"] = dateStr(t.getValueOfTransactionDate());
    glPayload["currencyCode"] = account.getValueOfCurrencyCode();
    glPayload["amount"] = amount.toString(false);
    glPayload["runningBalance"] = newBalance.toString(false);
    co_await turbo::outbox::writeEvent(txn, ctx, "savingsaccount", accountId, "savingsaccount.gl_posting",
                                       glPayload);
    co_return t.getValueOfId();
}

drogon::Task<std::string> DepositAccountManagementService::computeInterestForPeriod(
    Txn txn, const std::string &accountId, const std::string &fromDate, const std::string &toDate,
    const std::string &annualRatePercent, int daysInYear) {
    if (daysInYear <= 0) daysInYear = 365;
    const Date from = dateOr(fromDate, Date::now());
    const Date to = dateOr(toDate, Date::now());
    if (to.microSecondsSinceEpoch() <= from.microSecondsSinceEpoch()) co_return "0";

    auto rateMoney = turbo::Money::parse(annualRatePercent).value_or(turbo::Money());
    if (rateMoney.isZero()) co_return "0";

    // Balance in effect immediately before `from`.
    Mapper<m::SavingsAccountTransaction> txMapper(txn);
    txMapper.orderBy(m::SavingsAccountTransaction::Cols::_transaction_date, SortOrder::DESC).limit(1);
    auto priorRows = co_await txMapper.findBy(
        Criteria(m::SavingsAccountTransaction::Cols::_savings_account_id, accountId) &&
        Criteria(m::SavingsAccountTransaction::Cols::_is_reversed, false) &&
        Criteria(m::SavingsAccountTransaction::Cols::_transaction_date, CompareOperator::LT, fromDate));
    turbo::Money balance = priorRows.empty()
                               ? turbo::Money()
                               : turbo::Money::parse(priorRows.front().getValueOfRunningBalanceDerived())
                                     .value_or(turbo::Money());

    Mapper<m::SavingsAccountTransaction> segMapper(txn);
    segMapper.orderBy(m::SavingsAccountTransaction::Cols::_transaction_date, SortOrder::ASC);
    auto segRows = co_await segMapper.findBy(
        Criteria(m::SavingsAccountTransaction::Cols::_savings_account_id, accountId) &&
        Criteria(m::SavingsAccountTransaction::Cols::_is_reversed, false) &&
        Criteria(m::SavingsAccountTransaction::Cols::_transaction_date, CompareOperator::GE, fromDate) &&
        Criteria(m::SavingsAccountTransaction::Cols::_transaction_date, CompareOperator::LT, toDate));

    turbo::Money accrued;
    Date segStart = from;
    for (const auto &t : segRows) {
        const Date txDate = t.getValueOfTransactionDate();
        const auto days = daysBetween(segStart, txDate);
        if (days > 0) {
            auto annualInterest = balance.timesRatio(rateMoney.micros(), 100LL * turbo::Money::kScale);
            accrued += annualInterest.timesRatio(days, daysInYear);
            segStart = txDate;
        }
        balance = turbo::Money::parse(t.getValueOfRunningBalanceDerived()).value_or(balance);
    }
    const auto finalDays = daysBetween(segStart, to);
    if (finalDays > 0) {
        auto annualInterest = balance.timesRatio(rateMoney.micros(), 100LL * turbo::Money::kScale);
        accrued += annualInterest.timesRatio(finalDays, daysInYear);
    }
    co_return accrued.toString(false);
}

drogon::Task<std::string> DepositAccountManagementService::computeAccruedInterest(
    Txn txn, const std::string &accountId, const std::string &asOfDate) {
    auto account = co_await Mapper<m::SavingsAccount>(txn).findByPrimaryKey(accountId);
    std::string fromDate;
    if (account.getLastInterestCalculationDate())
        fromDate = dateStr(account.getValueOfLastInterestCalculationDate());
    else if (account.getActivatedOnDate())
        fromDate = dateStr(account.getValueOfActivatedOnDate());
    else
        co_return "0";
    co_return co_await computeInterestForPeriod(txn, accountId, fromDate, asOfDate,
                                                account.getValueOfNominalAnnualInterestRate(),
                                                account.getValueOfInterestCalculationDaysInYearType());
}

Json::Value DepositAccountManagementService::calculateFdInterest(const turbo::RequestContext &ctx,
                                                                  const Json::Value &query) {
    requirePermission(ctx, "READ_FIXEDDEPOSITPRODUCT");
    const auto principal = moneyOr(query, "principalAmount");
    const auto rateStr = asStringOr(query, "annualInterestRate", "0");
    const int tenureDays = asIntOr(query, "tenureInDays", 0);
    const int daysInYear = asIntOr(query, "daysInYear", 365);
    auto rateMoney = turbo::Money::parse(rateStr).value_or(turbo::Money());
    turbo::Money interest;
    if (tenureDays > 0 && !principal.isZero() && !rateMoney.isZero()) {
        auto annual = principal.timesRatio(rateMoney.micros(), 100LL * turbo::Money::kScale);
        interest = annual.timesRatio(tenureDays, daysInYear <= 0 ? 365 : daysInYear);
    }
    Json::Value j;
    j["principalAmount"] = principal.toString(false);
    j["annualInterestRate"] = rateMoney.toString(false);
    j["tenureInDays"] = tenureDays;
    j["interestEarned"] = interest.toString(false);
    j["maturityAmount"] = (principal + interest).toString(false);
    return j;
}

