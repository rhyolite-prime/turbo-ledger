drogon::Task<Json::Value> DepositAccountManagementService::handleAccountChargeCommand(
    const turbo::RequestContext &ctx, std::string accountId, std::string chargeId, std::string command,
    Json::Value body) {
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    Mapper<m::SavingsAccountCharge> mapper(txn);
    m::SavingsAccountCharge row;
    try {
        row = co_await mapper.findByPrimaryKey(chargeId);
    } catch (const UnexpectedRows &) {
        throw ApiError(drogon::k404NotFound, "Savings account charge not found",
                       "error.msg.savingsaccountcharge.not.found");
    }
    const auto outstanding = turbo::Money::parse(row.getValueOfAmountOutstandingDerived()).value_or(turbo::Money());
    if (command == "pay") {
        requirePermission(ctx, "CREATE_SAVINGSACCOUNTCHARGE");
        if (row.getValueOfIsPaidDerived() || row.getValueOfIsWaived())
            throw ApiError(drogon::k409Conflict, "Charge is already settled",
                           "error.msg.savingsaccountcharge.already.settled");
        const auto payDate = asStringOr(body, "transactionDate", dateStr(Date::now()));
        co_await postTransaction(txn, ctx, accountId, kTxnFeeCharge, payDate, outstanding.toString(false),
                                 "Charge payment");
        const auto paid = turbo::Money::parse(row.getValueOfAmountPaidDerived()).value_or(turbo::Money());
        row.setAmountPaidDerived((paid + outstanding).toString(false));
        row.setAmountOutstandingDerived("0");
        row.setIsPaidDerived(true);
    } else if (command == "waive") {
        requirePermission(ctx, "UPDATE_SAVINGSACCOUNTCHARGE");
        if (row.getValueOfIsPaidDerived() || row.getValueOfIsWaived())
            throw ApiError(drogon::k409Conflict, "Charge is already settled",
                           "error.msg.savingsaccountcharge.already.settled");
        row.setAmountWaivedDerived(outstanding.toString(false));
        row.setAmountOutstandingDerived("0");
        row.setIsWaived(true);
        co_await turbo::outbox::writeEvent(txn, ctx, "savingsaccounttransaction", chargeId,
                                           "savingsaccounttransaction.chargewaived",
                                           accountChargeJson(row));
    } else if (command == "inactivate") {
        requirePermission(ctx, "UPDATE_SAVINGSACCOUNTCHARGE");
        row.setIsActive(false);
        row.setInactivatedOnDate(Date::now());
    } else {
        throw ApiError(drogon::k400BadRequest, "Unknown command: " + command,
                       "error.msg.savingsaccountcharge.unknown.command");
    }
    row.setUpdatedBy(userIdOr(ctx));
    co_await mapper.update(row);
    co_await turbo::outbox::writeEvent(txn, ctx, "savingsaccountcharge", chargeId,
                                       "savingsaccountcharge." + command, body);
    co_return co_await accountChargeToJson(txn, chargeId);
}

