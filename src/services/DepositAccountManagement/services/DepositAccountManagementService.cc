drogon::Task<Json::Value> DepositAccountManagementService::createCharge(const turbo::RequestContext &ctx,
                                                                        Json::Value body) {
    requirePermission(ctx, "CREATE_CHARGE");
    const auto name = asStringOr(body, "name");
    const auto currencyCode = asStringOr(body, "currencyCode", "USD");
    const auto amount = moneyOr(body, "amount");
    if (name.empty() || amount.isZero())
        throw ApiError(drogon::k400BadRequest, "name and a non-zero amount are required",
                       "error.msg.charge.invalid");

    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    m::Charge row;
    row.setName(name);
    row.setCurrencyCode(currencyCode);
    row.setChargeAppliesTo(asIntOr(body, "chargeAppliesTo", 1));
    row.setChargeTimeType(asIntOr(body, "chargeTimeType", kChargeTimeSpecifiedDueDate));
    row.setChargeCalculationType(asIntOr(body, "chargeCalculationType", kChargeCalcFlat));
    row.setAmount(amount.toString(false));
    if (body.isMember("chargePaymentMode")) row.setChargePaymentMode(asIntOr(body, "chargePaymentMode", 0));
    if (body.isMember("feeOnMonth")) row.setFeeOnMonth(asIntOr(body, "feeOnMonth", 0));
    if (body.isMember("feeOnDay")) row.setFeeOnDay(asIntOr(body, "feeOnDay", 0));
    if (body.isMember("feeInterval")) row.setFeeInterval(asIntOr(body, "feeInterval", 0));
    row.setIsPenalty(asBoolOr(body, "penalty", false));
    row.setIsActive(asBoolOr(body, "active", true));
    row.setIsFreeWithdrawal(asBoolOr(body, "isFreeWithdrawal", false));
    if (body.isMember("freeWithdrawalChargeFrequency"))
        row.setFreeWithdrawalChargeFrequency(asIntOr(body, "freeWithdrawalChargeFrequency", 0));
    if (body.isMember("minCap")) row.setMinCap(moneyOr(body, "minCap").toString(false));
    if (body.isMember("maxCap")) row.setMaxCap(moneyOr(body, "maxCap").toString(false));
    row.setCreatedBy(userIdOr(ctx));
    row.setUpdatedBy(userIdOr(ctx));

    row = co_await Mapper<m::Charge>(txn).insert(row);
    co_await turbo::outbox::writeEvent(txn, ctx, "charge", row.getValueOfId(), "charge.created",
                                       chargeJson(row));
    co_return chargeJson(row);
}

