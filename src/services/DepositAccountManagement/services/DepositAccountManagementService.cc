drogon::Task<Json::Value> DepositAccountManagementService::addAccountCharge(
    const turbo::RequestContext &ctx, std::string accountId, Json::Value body) {
    requirePermission(ctx, "CREATE_SAVINGSACCOUNTCHARGE");
    const auto chargeId = asStringOr(body, "chargeId");
    if (chargeId.empty())
        throw ApiError(drogon::k400BadRequest, "chargeId is required", "error.msg.savingsaccountcharge.invalid");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    try {
        co_await Mapper<m::SavingsAccount>(txn).findByPrimaryKey(accountId);
    } catch (const UnexpectedRows &) {
        throw ApiError(drogon::k404NotFound, "Savings account not found", "error.msg.savingsaccount.not.found");
    }
    m::Charge charge;
    try {
        charge = co_await Mapper<m::Charge>(txn).findByPrimaryKey(chargeId);
    } catch (const UnexpectedRows &) {
        throw ApiError(drogon::k404NotFound, "Charge not found", "error.msg.charge.not.found");
    }
    m::SavingsAccountCharge row;
    row.setSavingsAccountId(accountId);
    row.setChargeId(chargeId);
    row.setChargeTimeType(charge.getValueOfChargeTimeType());
    if (body.isMember("dueDate")) row.setDueDate(dateOr(asStringOr(body, "dueDate"), Date::now()));
    if (charge.getFeeInterval()) row.setFeeInterval(charge.getValueOfFeeInterval());
    const auto amount = moneyOr(body, "amount", turbo::Money::parse(charge.getValueOfAmount()).value_or(turbo::Money()));
    row.setAmount(amount.toString(false));
    row.setAmountPaidDerived("0");
    row.setAmountWaivedDerived("0");
    row.setAmountOutstandingDerived(amount.toString(false));
    row.setIsPaidDerived(false);
    row.setIsWaived(false);
    row.setIsActive(true);
    row.setCreatedBy(userIdOr(ctx));
    row.setUpdatedBy(userIdOr(ctx));
    row = co_await Mapper<m::SavingsAccountCharge>(txn).insert(row);

    if (charge.getValueOfChargeTimeType() == kChargeTimeSavingsActivation ||
        charge.getValueOfChargeTimeType() == kChargeTimeSpecifiedDueDate) {
        // Flat due-immediately charges post straight away; recurring ones
        // (annual/monthly/withdrawal/overdraft fee) are collected by their
        // own trigger (command handler / future scheduled job).
    }
    co_await turbo::outbox::writeEvent(txn, ctx, "savingsaccountcharge", row.getValueOfId(),
                                       "savingsaccountcharge.created", accountChargeJson(row));
    co_return accountChargeJson(row);
}

