drogon::Task<Json::Value> DepositAccountManagementService::applyAccountCommand(
    Txn txn, const turbo::RequestContext &ctx, int depositType, const std::string &id,
    const std::string &command, const Json::Value &body) {
    Mapper<m::SavingsAccount> mapper(txn);
    m::SavingsAccount row;
    try {
        row = co_await mapper.findByPrimaryKey(id);
    } catch (const UnexpectedRows &) {
        throw ApiError(drogon::k404NotFound, "Savings account not found", "error.msg.savingsaccount.not.found");
    }
    if (row.getValueOfDepositType() != depositType)
        throw ApiError(drogon::k404NotFound, "Savings account not found", "error.msg.savingsaccount.not.found");
    const int status = row.getValueOfStatus();
    // Lifecycle-command permission codes are account-scoped (e.g.
    // APPROVE_SAVINGSACCOUNT, CLOSE_FIXEDDEPOSITACCOUNT) — distinct from the
    // products-catalog codes built by depositTypeProductPermission().
    const std::string label = depositTypeLabel(depositType) + "ACCOUNT";

    auto invalidTransition = [&]() {
        throw ApiError(drogon::k409Conflict,
                       "Command '" + command + "' is not valid for account status " +
                           accountStatusLabel(status),
                       "error.msg.savingsaccount.invalid.transition");
    };

    Json::Value extra(Json::objectValue);
    std::string eventType = "savingsaccount." + command;

    if (command == "approve") {
        requirePermission(ctx, "APPROVE_" + label);
        if (status != kStatusSubmittedAndPendingApproval) invalidTransition();
        row.setStatus(kStatusApproved);
        row.setApprovedOnDate(dateOr(asStringOr(body, "approvedOnDate"), Date::now()));
        row.setApprovedBy(userIdOr(ctx));
    } else if (command == "undoApproval") {
        requirePermission(ctx, "APPROVE_" + label);
        if (status != kStatusApproved) invalidTransition();
        row.setStatus(kStatusSubmittedAndPendingApproval);
        row.setApprovedOnDateToNull();
        row.setApprovedByToNull();
    } else if (command == "reject") {
        requirePermission(ctx, "REJECT_" + label);
        if (status != kStatusSubmittedAndPendingApproval) invalidTransition();
        row.setStatus(kStatusRejected);
        row.setRejectedOnDate(dateOr(asStringOr(body, "rejectedOnDate"), Date::now()));
        row.setRejectedBy(userIdOr(ctx));
    } else if (command == "withdrawnByApplicant") {
        requirePermission(ctx, "WITHDRAW_" + label);
        if (status != kStatusSubmittedAndPendingApproval && status != kStatusApproved) invalidTransition();
        row.setStatus(kStatusWithdrawn);
        row.setWithdrawnOnDate(dateOr(asStringOr(body, "withdrawnOnDate"), Date::now()));
        row.setWithdrawnBy(userIdOr(ctx));
    } else if (command == "assignSavingsOfficer") {
        requirePermission(ctx, "ASSIGNSTAFF_" + label);
        const auto staffId = asStringOr(body, "fieldOfficerId", asStringOr(body, "staffId"));
        if (staffId.empty())
            throw ApiError(drogon::k400BadRequest, "fieldOfficerId is required",
                           "error.msg.savingsaccount.fieldofficer.required");
        row.setFieldOfficerId(staffId);
    } else if (command == "unassignSavingsOfficer") {
        requirePermission(ctx, "ASSIGNSTAFF_" + label);
        row.setFieldOfficerIdToNull();
    } else if (command == "activate") {
        requirePermission(ctx, "ACTIVATE_" + label);
        if (status != kStatusApproved) invalidTransition();
        const auto activationDate = dateOr(asStringOr(body, "activatedOnDate"), Date::now());
        row.setStatus(kStatusActive);
        row.setActivatedOnDate(activationDate);
        row.setActivatedBy(userIdOr(ctx));
        row.setLastInterestCalculationDate(activationDate);
        co_await mapper.update(row);

        if (depositType != kDepositTypeSavings) {
            auto terms = co_await Mapper<m::DepositAccountTermAndPreclosure>(txn).findBy(
                Criteria(m::DepositAccountTermAndPreclosure::Cols::_savings_account_id, id));
            if (!terms.empty()) {
                auto term = terms.front();
                if (term.getDepositAmount() && turbo::Money::parse(term.getValueOfDepositAmount())
                                                    .value_or(turbo::Money())
                                                    .isNegative() == false &&
                    !turbo::Money::parse(term.getValueOfDepositAmount()).value_or(turbo::Money()).isZero()) {
                    co_await postTransaction(txn, ctx, id, kTxnDeposit, dateStr(activationDate),
                                             term.getValueOfDepositAmount(), "Initial deposit on activation");
                }
                if (depositType == kDepositTypeRecurringDeposit && term.getDepositPeriod()) {
                    const int months = term.getValueOfDepositPeriod();
                    const Date firstDue = term.getExpectedFirstdepositOnDate()
                                              ? term.getValueOfExpectedFirstdepositOnDate()
                                              : activationDate;
                    for (int i = 0; i < months; ++i) {
                        m::RecurringDepositScheduleInstallment inst;
                        inst.setSavingsAccountId(id);
                        inst.setInstallmentNumber(i + 1);
                        // Simple monthly schedule: +i months, approximated as +i*30 days
                        // (no calendar/holiday awareness this phase — documented scope trim).
                        inst.setDueDate(Date(firstDue.microSecondsSinceEpoch() +
                                             static_cast<std::int64_t>(i) * 30LL * 86400000000LL));
                        inst.setDepositAmount(term.getDepositAmount() ? term.getValueOfDepositAmount() : "0");
                        inst.setDepositAmountCompletedDerived("0");
                        inst.setIsObligationMet(false);
                        co_await Mapper<m::RecurringDepositScheduleInstallment>(txn).insert(inst);
                    }
                }
                if (term.getDepositPeriod() && !term.getMaturityDate()) {
                    const int freqType = term.getDepositPeriodFrequencyType() ? term.getValueOfDepositPeriodFrequencyType() : 2;
                    const int period = term.getValueOfDepositPeriod();
                    std::int64_t totalDays = freqType == 0 ? period : freqType == 1 ? period * 30LL : period * 365LL;
                    term.setMaturityDate(
                        Date(activationDate.microSecondsSinceEpoch() + totalDays * 86400000000LL));
                    co_await Mapper<m::DepositAccountTermAndPreclosure>(txn).update(term);
                }
            }
        }
        co_await turbo::outbox::writeEvent(txn, ctx, "savingsaccount", id, eventType, body);
        co_return co_await accountToJson(txn, id);
    } else if (command == "close" || command == "prematureClose") {
        requirePermission(ctx, "CLOSE_" + label);
        if (status != kStatusActive) invalidTransition();
        const auto closureDate = dateOr(asStringOr(body, "closedOnDate"), Date::now());

        if (depositType != kDepositTypeSavings && command == "prematureClose") {
            auto terms = co_await Mapper<m::DepositAccountTermAndPreclosure>(txn).findBy(
                Criteria(m::DepositAccountTermAndPreclosure::Cols::_savings_account_id, id));
            if (!terms.empty() && terms.front().getValueOfPreClosurePenalApplicable() &&
                row.getActivatedOnDate()) {
                const auto &term = terms.front();
                auto nominal = turbo::Money::parse(row.getValueOfNominalAnnualInterestRate()).value_or(turbo::Money());
                auto penal = term.getPreClosurePenalInterest()
                                ? turbo::Money::parse(term.getValueOfPreClosurePenalInterest()).value_or(turbo::Money())
                                : turbo::Money();
                auto effective = nominal.isNegative() || penal.micros() > nominal.micros()
                                    ? turbo::Money()
                                    : nominal - penal;
                const auto recomputed = co_await computeInterestForPeriod(
                    txn, id, dateStr(row.getValueOfActivatedOnDate()), dateStr(closureDate),
                    effective.toString(false), row.getValueOfInterestCalculationDaysInYearType());
                const auto recomputedMoney = turbo::Money::parse(recomputed).value_or(turbo::Money());
                const auto alreadyPosted =
                    turbo::Money::parse(row.getValueOfTotalInterestPostedDerived()).value_or(turbo::Money());
                const auto adjustment = recomputedMoney - alreadyPosted;
                if (!adjustment.isZero()) {
                    co_await postTransaction(txn, ctx, id,
                                             adjustment.isNegative() ? kTxnWithdrawal : kTxnInterestPosting,
                                             dateStr(closureDate),
                                             (adjustment.isNegative() ? -adjustment : adjustment).toString(false),
                                             "Premature closure interest adjustment (penalty rate applied)");
                }
                extra["premature closure interest recomputed"] = recomputed;
            }
        }

        // Re-fetch: postTransaction() above may have mutated account_balance_derived.
        row = co_await mapper.findByPrimaryKey(id);
        const auto balance = turbo::Money::parse(row.getValueOfAccountBalanceDerived()).value_or(turbo::Money());
        if (!balance.isZero()) {
            const auto toSavingsAccountId = asStringOr(body, "toSavingsAccountId");
            if (!toSavingsAccountId.empty()) {
                co_await postTransaction(txn, ctx, id, kTxnTransferOut, dateStr(closureDate),
                                         balance.toString(false), "Closure proceeds transferred out");
                co_await postTransaction(txn, ctx, toSavingsAccountId, kTxnTransferIn, dateStr(closureDate),
                                         balance.toString(false), "Closure proceeds transferred in");
            } else {
                co_await postTransaction(txn, ctx, id, kTxnWithdrawal, dateStr(closureDate),
                                         balance.toString(false), "Closure proceeds withdrawn");
            }
        }
        row = co_await mapper.findByPrimaryKey(id);
        row.setStatus(command == "prematureClose" ? kStatusPrematureClosed : kStatusClosed);
        row.setClosedOnDate(closureDate);
        row.setClosedBy(userIdOr(ctx));
    } else if (command == "calculateInterest") {
        requirePermission(ctx, "READ_" + label);
        if (status != kStatusActive) invalidTransition();
        const auto asOf = asStringOr(body, "transactionDate", dateStr(Date::now()));
        const auto accrued = co_await computeAccruedInterest(txn, id, asOf);
        auto j = accountJson(row);
        j["interestCalculated"] = moneyJson(accrued);
        j["asOfDate"] = asOf;
        co_return j;
    } else if (command == "postInterest") {
        requirePermission(ctx, "CREATE_" + label);
        if (status != kStatusActive) invalidTransition();
        if (row.getValueOfIsInterestBlocked())
            throw ApiError(drogon::k409Conflict, "Interest posting is blocked for this account",
                           "error.msg.savingsaccount.interest.blocked");
        const auto asOf = asStringOr(body, "transactionDate", dateStr(Date::now()));
        const auto accrued = co_await computeAccruedInterest(txn, id, asOf);
        if (!turbo::Money::parse(accrued).value_or(turbo::Money()).isZero())
            co_await postTransaction(txn, ctx, id, kTxnInterestPosting, asOf, accrued, "Interest posting");
        row = co_await mapper.findByPrimaryKey(id);
        row.setLastInterestCalculationDate(dateOr(asOf, Date::now()));
    } else if (command == "updateDepositAmount") {
        requirePermission(ctx, "UPDATE_" + label);
        if (depositType != kDepositTypeRecurringDeposit)
            throw ApiError(drogon::k400BadRequest, "updateDepositAmount only applies to recurring deposits",
                           "error.msg.savingsaccount.command.invalid");
        const auto newAmount = moneyOr(body, "depositAmount");
        if (newAmount.isZero())
            throw ApiError(drogon::k400BadRequest, "depositAmount is required",
                           "error.msg.savingsaccount.depositamount.required");
        auto terms = co_await Mapper<m::DepositAccountTermAndPreclosure>(txn).findBy(
            Criteria(m::DepositAccountTermAndPreclosure::Cols::_savings_account_id, id));
        if (!terms.empty()) {
            auto term = terms.front();
            term.setDepositAmount(newAmount.toString(false));
            co_await Mapper<m::DepositAccountTermAndPreclosure>(txn).update(term);
        }
        auto installments = co_await Mapper<m::RecurringDepositScheduleInstallment>(txn).findBy(
            Criteria(m::RecurringDepositScheduleInstallment::Cols::_savings_account_id, id) &&
            Criteria(m::RecurringDepositScheduleInstallment::Cols::_is_obligation_met, false));
        for (auto &inst : installments) {
            inst.setDepositAmount(newAmount.toString(false));
            co_await Mapper<m::RecurringDepositScheduleInstallment>(txn).update(inst);
        }
    } else {
        throw ApiError(drogon::k400BadRequest, "Unknown command: " + command,
                       "error.msg.savingsaccount.unknown.command");
    }

    row.setUpdatedBy(userIdOr(ctx));
    co_await mapper.update(row);
    co_await turbo::outbox::writeEvent(txn, ctx, "savingsaccount", id, eventType, body);
    auto result = co_await accountToJson(txn, id);
    for (const auto &key : extra.getMemberNames()) result[key] = extra[key];
    co_return result;
}

drogon::Task<Json::Value> DepositAccountManagementService::handleAccountCommand(
    const turbo::RequestContext &ctx, int depositType, std::string id, std::string command,
    Json::Value body) {
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    co_return co_await applyAccountCommand(txn, ctx, depositType, id, command, body);
}

