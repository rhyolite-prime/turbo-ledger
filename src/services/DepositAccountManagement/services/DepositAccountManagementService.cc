Date dateOr(const std::string &text, const Date &fallback) {
    if (text.empty()) return fallback;
    return Date::fromDbStringLocal(text.size() == 10 ? text + " 00:00:00" : text);
}
std::string dateStr(const Date &d) { return d.toDbStringLocal().substr(0, 10); }

std::string asStringOr(const Json::Value &v, const char *key, const std::string &fallback = "") {
    return v.isMember(key) && !v[key].isNull() ? v[key].asString() : fallback;
}
bool asBoolOr(const Json::Value &v, const char *key, bool fallback) {
    return v.isMember(key) && v[key].isBool() ? v[key].asBool() : fallback;
}
int asIntOr(const Json::Value &v, const char *key, int fallback) {
    return v.isMember(key) && v[key].isNumeric() ? v[key].asInt() : fallback;
}
std::string userIdOr(const turbo::RequestContext &ctx) {
    return ctx.userId.empty() ? kZeroUuid : ctx.userId;
}
Json::Value moneyJson(const std::string &dbNumeric) {
    if (dbNumeric.empty()) return Json::Value();
    auto parsed = turbo::Money::parse(dbNumeric);
    return parsed ? Json::Value(parsed->toString(false)) : Json::Value(dbNumeric);
}
turbo::Money moneyOr(const Json::Value &v, const char *key, turbo::Money fallback = turbo::Money()) {
    if (!v.isMember(key) || v[key].isNull()) return fallback;
    auto parsed = turbo::Money::parse(v[key].isString() ? v[key].asString() : v[key].asString());
    return parsed ? *parsed : fallback;
}
std::int64_t daysBetween(const Date &a, const Date &b) {
    constexpr std::int64_t kMicrosPerDay = 86400000000LL;
    return (b.microSecondsSinceEpoch() - a.microSecondsSinceEpoch()) / kMicrosPerDay;
}

// Base word used to build Fineract-shaped permission codes. NOTE: on its own
// this does NOT disambiguate products from accounts (both are keyed off the
// same deposit_type) — callers must append "PRODUCT" or "ACCOUNT" themselves
// (see depositTypeProductPermission()/depositTypeAccountPermission() below),
// otherwise e.g. READ_SAVINGSPRODUCT and READ_SAVINGSACCOUNT would collapse
// onto the same code and a caller permissioned for one resource could read
// the other.
std::string depositTypeLabel(int depositType) {
    switch (depositType) {
        case kDepositTypeSavings: return "SAVINGS";
        case kDepositTypeFixedDeposit: return "FIXEDDEPOSIT";
        case kDepositTypeRecurringDeposit: return "RECURRINGDEPOSIT";
        default: return "UNKNOWN";
    }
}

/// Permission code for a products-catalog verb, e.g. "READ_SAVINGSPRODUCT".
std::string depositTypeProductPermission(const std::string &verb, int depositType) {
    return verb + "_" + depositTypeLabel(depositType) + "PRODUCT";
}

/// Permission code for an account-resource verb (CRUD or lifecycle command),
/// e.g. "READ_SAVINGSACCOUNT" / "APPROVE_FIXEDDEPOSITACCOUNT".
std::string depositTypeAccountPermission(const std::string &verb, int depositType) {
    return verb + "_" + depositTypeLabel(depositType) + "ACCOUNT";
}

std::string accountStatusLabel(int status) {
    switch (status) {
        case kStatusSubmittedAndPendingApproval: return "Submitted and pending approval";
        case kStatusApproved: return "Approved";
        case kStatusActive: return "Active";
        case kStatusWithdrawn: return "Withdrawn by applicant";
        case kStatusRejected: return "Rejected";
        case kStatusClosed: return "Closed";
        case kStatusPrematureClosed: return "Prematurely closed";
        case kStatusMatured: return "Matured";
        default: return "Unknown";
    }
}

