    try {
        row = co_await Mapper<m::SavingsProduct>(txn).insert(row);
    } catch (const DrogonDbException &e) {
        throw ApiError(drogon::k400BadRequest,
                       std::string("Could not create product: ") + e.base().what(),
                       "error.msg.savingsproduct.duplicate.shortname");
    }
    if (body.isMember("charges") && body["charges"].isArray()) {
        for (const auto &c : body["charges"]) {
            m::SavingsProductCharge pc;
            pc.setProductId(row.getValueOfId());
            pc.setChargeId(c.asString());
            co_await Mapper<m::SavingsProductCharge>(txn).insert(pc);
        }
    }
    co_await turbo::outbox::writeEvent(txn, ctx, "savingsproduct", row.getValueOfId(),
                                       "savingsproduct.created", productJson(row));
    co_return co_await productToJson(txn, row.getValueOfId());
