    if (r.getOverdraftLimit()) j["overdraftLimit"] = moneyJson(r.getValueOfOverdraftLimit());
    if (r.getMinRequiredBalance()) j["minRequiredBalance"] = moneyJson(r.getValueOfMinRequiredBalance());
    if (r.getSubmittedOnDate()) j["submittedOnDate"] = dateStr(r.getValueOfSubmittedOnDate());
    if (r.getApprovedOnDate()) j["approvedOnDate"] = dateStr(r.getValueOfApprovedOnDate());
    if (r.getActivatedOnDate()) j["activatedOnDate"] = dateStr(r.getValueOfActivatedOnDate());
    if (r.getRejectedOnDate()) j["rejectedOnDate"] = dateStr(r.getValueOfRejectedOnDate());
    if (r.getWithdrawnOnDate()) j["withdrawnOnDate"] = dateStr(r.getValueOfWithdrawnOnDate());
    if (r.getClosedOnDate()) j["closedOnDate"] = dateStr(r.getValueOfClosedOnDate());
