namespace {
Json::Value accountChargeJson(const m::SavingsAccountCharge &r) {
    Json::Value j;
    j["id"] = r.getValueOfId();
    j["savingsAccountId"] = r.getValueOfSavingsAccountId();
    j["chargeId"] = r.getValueOfChargeId();
    j["chargeTimeType"] = r.getValueOfChargeTimeType();
    if (r.getDueDate()) j["dueDate"] = dateStr(r.getValueOfDueDate());
    if (r.getFeeInterval()) j["feeInterval"] = r.getValueOfFeeInterval();
    j["amount"] = moneyJson(r.getValueOfAmount());
    j["amountPaid"] = moneyJson(r.getValueOfAmountPaidDerived());
    j["amountWaived"] = moneyJson(r.getValueOfAmountWaivedDerived());
    j["amountOutstanding"] = moneyJson(r.getValueOfAmountOutstandingDerived());
    j["paid"] = r.getValueOfIsPaidDerived();
    j["waived"] = r.getValueOfIsWaived();
    j["active"] = r.getValueOfIsActive();
    return j;
}
}  // namespace

