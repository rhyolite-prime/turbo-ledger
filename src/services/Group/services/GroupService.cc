drogon::Task<Json::Value> GroupService::listEntities(const turbo::RequestContext &ctx, bool isCenter,
                                                     const std::string &officeId,
                                                     const std::string &staffId, const std::string &status,
                                                     const std::string &nameLike, int offset, int limit) {
    requirePermission(ctx, isCenter ? "READ_CENTER" : "READ_GROUP");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    const auto levelId = co_await resolveLevelId(txn, isCenter);
    Mapper<m::Group> mapper(txn);
    Criteria crit(m::Group::Cols::_level_id, levelId);
    if (!officeId.empty()) crit = crit && Criteria(m::Group::Cols::_office_id, officeId);
    if (!staffId.empty()) crit = crit && Criteria(m::Group::Cols::_staff_id, staffId);
    if (!status.empty()) crit = crit && Criteria(m::Group::Cols::_status_enum, std::stoi(status));
    if (!nameLike.empty())
        crit = crit && Criteria(m::Group::Cols::_display_name, CompareOperator::Like, "%" + nameLike + "%");

    const auto total = co_await mapper.count(crit);
    mapper.orderBy(m::Group::Cols::_display_name).limit(limit).offset(offset);
    auto rows = co_await mapper.findBy(crit);
    Json::Value items(Json::arrayValue);
    for (const auto &r : rows) items.append(entityBaseJson(r));
    co_return turbo::pagedResult(static_cast<std::int64_t>(total), items);
}

