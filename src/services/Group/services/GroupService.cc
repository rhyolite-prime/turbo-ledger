drogon::Task<Json::Value> GroupService::listGroupLevels(const turbo::RequestContext &ctx) {
    requirePermission(ctx, "READ_GROUPLEVEL");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    auto rows = co_await Mapper<m::GroupLevel>(txn).orderBy(m::GroupLevel::Cols::_super_parent,
                                                            SortOrder::DESC)
                    .findAll();
    Json::Value items(Json::arrayValue);
    for (const auto &r : rows) {
        Json::Value j;
        j["id"] = r.getValueOfId();
        if (r.getParentLevelId()) j["parentLevelId"] = r.getValueOfParentLevelId();
        j["levelName"] = r.getValueOfLevelName();
        j["superParent"] = r.getValueOfSuperParent();
        items.append(j);
    }
    co_return items;
}

drogon::Task<std::string> GroupService::resolveLevelId(Txn txn, bool isCenter) {
    const std::string levelName = isCenter ? "Center" : "Group";
    auto rows =
        co_await Mapper<m::GroupLevel>(txn).findBy(Criteria(m::GroupLevel::Cols::_level_name, levelName));
    if (rows.empty())
        throw ApiError(drogon::k500InternalServerError,
                       "Group level seed row '" + levelName +
                           "' is missing — has V003__phase7_group.sql been applied?",
                       "error.msg.grouplevel.not.found");
    co_return rows.front().getValueOfId();
}

drogon::Task<std::string> GroupService::generateAccountNumber(Txn txn, bool isCenter,
                                                              const std::string &seedId) {
    (void)txn;
    std::string digits;
    for (char c : seedId)
        if (isxdigit(static_cast<unsigned char>(c))) digits.push_back(c);
    co_return std::string(isCenter ? "CE" : "GR") + digits.substr(0, 10);
}

drogon::Task<Json::Value> GroupService::entityToJson(Txn txn, const std::string &id, bool isCenter) {
    Mapper<m::Group> mapper(txn);
    m::Group row;
    try {
        row = co_await mapper.findByPrimaryKey(id);
    } catch (const UnexpectedRows &) {
        throw ApiError(drogon::k404NotFound, isCenter ? "Center not found" : "Group not found",
                       isCenter ? "error.msg.center.not.found" : "error.msg.group.not.found");
    }
    const auto levelId = co_await resolveLevelId(txn, isCenter);
    if (row.getValueOfLevelId() != levelId)
        throw ApiError(drogon::k404NotFound, isCenter ? "Center not found" : "Group not found",
                       isCenter ? "error.msg.center.not.found" : "error.msg.group.not.found");

    Json::Value j = entityBaseJson(row);
    if (isCenter) {
        auto children = co_await Mapper<m::Group>(txn).findBy(Criteria(m::Group::Cols::_parent_id, id));
        Json::Value members(Json::arrayValue);
        for (const auto &c : children) members.append(entityBaseJson(c));
        j["groupMembers"] = members;
    } else {
        auto clients = co_await Mapper<m::GroupClient>(txn).findBy(Criteria(m::GroupClient::Cols::_group_id, id));
        Json::Value members(Json::arrayValue);
        for (const auto &c : clients) members.append(c.getValueOfClientId());
        j["clientMembers"] = members;

        auto roles = co_await Mapper<m::GroupRole>(txn).findBy(Criteria(m::GroupRole::Cols::_group_id, id));
        Json::Value roleArr(Json::arrayValue);
        for (const auto &r : roles) {
            Json::Value rj;
            rj["id"] = r.getValueOfId();
            rj["clientId"] = r.getValueOfClientId();
            rj["roleCvId"] = r.getValueOfRoleCvId();
            roleArr.append(rj);
        }
        j["roles"] = roleArr;
    }
    co_return j;
}

