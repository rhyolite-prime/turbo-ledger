constexpr const char *kZeroUuid = "00000000-0000-0000-0000-000000000000";

// groups.status_enum — matches the real Fineract GroupingTypeStatus values
// (and the column's own `DEFAULT 300` in the pg_dump baseline, i.e. "active
// unless told otherwise", which is exactly Fineract's own default).
constexpr int kStatusPending = 100;
constexpr int kStatusActive = 300;
constexpr int kStatusClosed = 600;

std::string statusLabel(int status) {
    switch (status) {
        case kStatusPending: return "pending";
        case kStatusActive: return "active";
        case kStatusClosed: return "closed";
        default: return "unknown";
    }
}

bool isSet(const std::string &uuid) { return !uuid.empty() && uuid != kZeroUuid; }

Date dateOr(const std::string &text, const Date &fallback) {
    if (text.empty()) return fallback;
    return Date::fromDbStringLocal(text);
}
std::string dateStr(const Date &d) { return d.toDbStringLocal(); }

std::string asStringOr(const Json::Value &v, const char *key, const std::string &fallback = "") {
    return v.isMember(key) && !v[key].isNull() ? v[key].asString() : fallback;
}

bool asBoolOr(const Json::Value &v, const char *key, bool fallback) {
    return v.isMember(key) && v[key].isBool() ? v[key].asBool() : fallback;
}

std::string userIdOr(const turbo::RequestContext &ctx) {
    return ctx.userId.empty() ? kZeroUuid : ctx.userId;
}

std::vector<std::string> stringArray(const Json::Value &body, const char *key) {
    std::vector<std::string> out;
    if (!body.isMember(key) || !body[key].isArray()) return out;
    for (const auto &v : body[key]) {
        const auto s = v.isString() ? v.asString() : (v.isObject() ? asStringOr(v, "clientId") : "");
        if (!s.empty()) out.push_back(s);
    }
    return out;
}

Json::Value entityBaseJson(const m::Group &row) {
    Json::Value j;
    j["id"] = row.getValueOfId();
    if (row.getExternalId() && !row.getValueOfExternalId().empty()) j["externalId"] = row.getValueOfExternalId();
    j["status"] = row.getValueOfStatusEnum();
    j["statusName"] = statusLabel(row.getValueOfStatusEnum());
    if (row.getActivationDate()) j["activationDate"] = dateStr(row.getValueOfActivationDate());
    j["officeId"] = row.getValueOfOfficeId();
    if (row.getStaffId() && isSet(row.getValueOfStaffId())) j["staffId"] = row.getValueOfStaffId();
    if (row.getParentId() && isSet(row.getValueOfParentId())) j["parentId"] = row.getValueOfParentId();
    j["levelId"] = row.getValueOfLevelId();
    j["name"] = row.getValueOfDisplayName();
    if (row.getHierarchy() && !row.getValueOfHierarchy().empty()) j["hierarchy"] = row.getValueOfHierarchy();
    if (row.getClosureReasonCvId() && isSet(row.getValueOfClosureReasonCvId()))
        j["closureReasonCvId"] = row.getValueOfClosureReasonCvId();
    if (row.getClosedonDate()) j["closedOnDate"] = dateStr(row.getValueOfClosedonDate());
    if (row.getSubmittedonDate()) j["submittedOnDate"] = dateStr(row.getValueOfSubmittedonDate());
    if (row.getActivatedonUserid() && isSet(row.getValueOfActivatedonUserid()))
        j["activatedOnUserId"] = row.getValueOfActivatedonUserid();
    if (row.getSubmittedonUserid() && isSet(row.getValueOfSubmittedonUserid()))
        j["submittedOnUserId"] = row.getValueOfSubmittedonUserid();
    j["accountNo"] = row.getValueOfAccountNo();
    return j;
}

