drogon::Task<Json::Value> GroupService::handleCommand(const turbo::RequestContext &ctx, bool isCenter,
                                                      const std::string &id, const std::string &command,
                                                      const Json::Value &body) {
    const std::string label = isCenter ? "CENTER" : "GROUP";
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    const auto levelId = co_await resolveLevelId(txn, isCenter);
    Mapper<m::Group> mapper(txn);
    m::Group row;
    try {
        row = co_await mapper.findByPrimaryKey(id);
    } catch (const UnexpectedRows &) {
        throw ApiError(drogon::k404NotFound, isCenter ? "Center not found" : "Group not found",
                       isCenter ? "error.msg.center.not.found" : "error.msg.group.not.found");
    }
    if (row.getValueOfLevelId() != levelId)
        throw ApiError(drogon::k404NotFound, isCenter ? "Center not found" : "Group not found",
                       isCenter ? "error.msg.center.not.found" : "error.msg.group.not.found");
    const int status = row.getValueOfStatusEnum();
    std::string eventType = (isCenter ? std::string("center.") : std::string("group.")) + command;

    auto invalidTransition = [&]() {
        throw ApiError(drogon::k409Conflict,
                       "Command '" + command + "' is not valid for status " + statusLabel(status),
                       isCenter ? "error.msg.center.invalid.transition" : "error.msg.group.invalid.transition");
    };

    // ---- membership/role commands: these don't touch `row` itself, so they
    // write their own outbox event and return directly rather than falling
    // through to the shared row-update tail below.
    if (!isCenter && command == "associateClients") {
        requirePermission(ctx, "ASSOCIATECLIENTS_GROUP");
        const auto clientIds = stringArray(body, "clientMembers");
        if (clientIds.empty())
            throw ApiError(drogon::k400BadRequest, "clientMembers must be a non-empty array",
                           "error.msg.group.members.required");
        for (const auto &clientId : clientIds) {
            auto existing = co_await Mapper<m::GroupClient>(txn).findBy(
                Criteria(m::GroupClient::Cols::_group_id, id) &&
                Criteria(m::GroupClient::Cols::_client_id, clientId));
            if (!existing.empty()) continue;
            m::GroupClient gc;
            gc.setGroupId(id);
            gc.setClientId(clientId);
            co_await Mapper<m::GroupClient>(txn).insert(gc);
        }
        co_await turbo::outbox::writeEvent(txn, ctx, "group", id, eventType, body);
        co_return co_await entityToJson(txn, id, isCenter);
    }
    if (!isCenter && command == "disassociateClients") {
        requirePermission(ctx, "ASSOCIATECLIENTS_GROUP");
        for (const auto &clientId : stringArray(body, "clientMembers")) {
            auto existing = co_await Mapper<m::GroupClient>(txn).findBy(
                Criteria(m::GroupClient::Cols::_group_id, id) &&
                Criteria(m::GroupClient::Cols::_client_id, clientId));
            for (auto &gc : existing) co_await Mapper<m::GroupClient>(txn).deleteOne(gc);
        }
        co_await turbo::outbox::writeEvent(txn, ctx, "group", id, eventType, body);
        co_return co_await entityToJson(txn, id, isCenter);
    }
    if (!isCenter && command == "transferClients") {
        requirePermission(ctx, "ASSOCIATECLIENTS_GROUP");
        const auto destGroupId = asStringOr(body, "destinationGroupId");
        if (destGroupId.empty())
            throw ApiError(drogon::k400BadRequest, "destinationGroupId is required",
                           "error.msg.group.destination.required");
        auto destRows = co_await Mapper<m::Group>(txn).findBy(Criteria(m::Group::Cols::_id, destGroupId) &&
                                                               Criteria(m::Group::Cols::_level_id, levelId));
        if (destRows.empty())
            throw ApiError(drogon::k404NotFound, "Destination group not found",
                           "error.msg.group.not.found");
        auto clientIds = stringArray(body, "clientMembers");
        if (clientIds.empty()) clientIds = stringArray(body, "clients");
        for (const auto &clientId : clientIds) {
            auto existing = co_await Mapper<m::GroupClient>(txn).findBy(
                Criteria(m::GroupClient::Cols::_group_id, id) &&
                Criteria(m::GroupClient::Cols::_client_id, clientId));
            for (auto &gc : existing) co_await Mapper<m::GroupClient>(txn).deleteOne(gc);
            auto atDest = co_await Mapper<m::GroupClient>(txn).findBy(
                Criteria(m::GroupClient::Cols::_group_id, destGroupId) &&
                Criteria(m::GroupClient::Cols::_client_id, clientId));
            if (atDest.empty()) {
                m::GroupClient gc;
                gc.setGroupId(destGroupId);
                gc.setClientId(clientId);
                co_await Mapper<m::GroupClient>(txn).insert(gc);
            }
        }
        co_await turbo::outbox::writeEvent(txn, ctx, "group", id, eventType, body);
        co_return co_await entityToJson(txn, id, isCenter);
    }
    if (!isCenter && command == "assignRole") {
        requirePermission(ctx, "ASSIGNROLE_GROUP");
        const auto clientId = asStringOr(body, "clientId");
        const auto roleCvId = asStringOr(body, "roleId", asStringOr(body, "roleCvId"));
        if (clientId.empty() || roleCvId.empty())
            throw ApiError(drogon::k400BadRequest, "clientId and roleId are required",
                           "error.msg.group.role.required");
        m::GroupRole gr;
        gr.setGroupId(id);
        gr.setClientId(clientId);
        gr.setRoleCvId(roleCvId);
        try {
            co_await Mapper<m::GroupRole>(txn).insert(gr);
        } catch (const DrogonDbException &e) {
            throw ApiError(drogon::k400BadRequest,
                           std::string("Could not assign role: ") + e.base().what(),
                           "error.msg.group.role.duplicate");
        }
        co_await turbo::outbox::writeEvent(txn, ctx, "group", id, eventType, body);
        co_return co_await entityToJson(txn, id, isCenter);
    }
    if (!isCenter && command == "unassignRole") {
        requirePermission(ctx, "ASSIGNROLE_GROUP");
        const auto roleRowId = asStringOr(body, "id");
        const auto clientId = asStringOr(body, "clientId");
        if (!roleRowId.empty()) {
            try {
                auto gr = co_await Mapper<m::GroupRole>(txn).findByPrimaryKey(roleRowId);
                if (gr.getValueOfGroupId() == id) co_await Mapper<m::GroupRole>(txn).deleteOne(gr);
            } catch (const UnexpectedRows &) {
                // already gone — treat as success.
            }
        } else if (!clientId.empty()) {
            auto matches = co_await Mapper<m::GroupRole>(txn).findBy(
                Criteria(m::GroupRole::Cols::_group_id, id) &&
                Criteria(m::GroupRole::Cols::_client_id, clientId));
            for (auto &gr : matches) co_await Mapper<m::GroupRole>(txn).deleteOne(gr);
        } else {
            throw ApiError(drogon::k400BadRequest, "id (role assignment id) or clientId is required",
                           "error.msg.group.role.required");
        }
        co_await turbo::outbox::writeEvent(txn, ctx, "group", id, eventType, body);
        co_return co_await entityToJson(txn, id, isCenter);
    }
    if (!isCenter && command == "updateRole") {
        requirePermission(ctx, "ASSIGNROLE_GROUP");
        const auto roleRowId = asStringOr(body, "id");
        const auto newRoleCvId = asStringOr(body, "roleId", asStringOr(body, "roleCvId"));
        if (roleRowId.empty() || newRoleCvId.empty())
            throw ApiError(drogon::k400BadRequest, "id and roleId are required",
                           "error.msg.group.role.required");
        m::GroupRole gr;
        try {
            gr = co_await Mapper<m::GroupRole>(txn).findByPrimaryKey(roleRowId);
        } catch (const UnexpectedRows &) {
            throw ApiError(drogon::k404NotFound, "Role assignment not found",
                           "error.msg.group.role.not.found");
        }
        if (gr.getValueOfGroupId() != id)
            throw ApiError(drogon::k404NotFound, "Role assignment not found",
                           "error.msg.group.role.not.found");
        gr.setRoleCvId(newRoleCvId);
        co_await Mapper<m::GroupRole>(txn).update(gr);
        co_await turbo::outbox::writeEvent(txn, ctx, "group", id, eventType, body);
        co_return co_await entityToJson(txn, id, isCenter);
    }
    if (isCenter && command == "associateGroups") {
        requirePermission(ctx, "ASSOCIATEGROUPS_CENTER");
        const auto groupIds = stringArray(body, "groupMembers");
        if (groupIds.empty())
            throw ApiError(drogon::k400BadRequest, "groupMembers must be a non-empty array",
                           "error.msg.center.members.required");
        const auto groupLevelId = co_await resolveLevelId(txn, false);
        for (const auto &childId : groupIds) {
            m::Group child;
            try {
                child = co_await Mapper<m::Group>(txn).findByPrimaryKey(childId);
            } catch (const UnexpectedRows &) {
                throw ApiError(drogon::k404NotFound, "Group not found: " + childId,
                               "error.msg.group.not.found");
            }
            if (child.getValueOfLevelId() != groupLevelId)
                throw ApiError(drogon::k400BadRequest, childId + " is not a Group-level entity",
                               "error.msg.center.member.invalid");
            child.setParentId(id);
            co_await Mapper<m::Group>(txn).update(child);
        }
        co_await turbo::outbox::writeEvent(txn, ctx, "center", id, eventType, body);
        co_return co_await entityToJson(txn, id, isCenter);
    }
    if (isCenter && command == "disassociateGroups") {
        requirePermission(ctx, "ASSOCIATEGROUPS_CENTER");
        for (const auto &childId : stringArray(body, "groupMembers")) {
            try {
                auto child = co_await Mapper<m::Group>(txn).findByPrimaryKey(childId);
                if (child.getValueOfParentId() == id) {
                    child.setParentId(kZeroUuid);
                    co_await Mapper<m::Group>(txn).update(child);
                }
            } catch (const UnexpectedRows &) {
                // unknown child group id — ignore.
            }
        }
        co_await turbo::outbox::writeEvent(txn, ctx, "center", id, eventType, body);
        co_return co_await entityToJson(txn, id, isCenter);
    }

    // ---- lifecycle/staff commands: mutate `row`, shared tail below.
    if (command == "activate") {
        requirePermission(ctx, "ACTIVATE_" + label);
        if (status != kStatusPending) invalidTransition();
        row.setStatusEnum(kStatusActive);
        row.setActivationDate(dateOr(asStringOr(body, "activationDate"), Date::now()));
        row.setActivatedonUserid(userIdOr(ctx));
    } else if (command == "close") {
        requirePermission(ctx, "CLOSE_" + label);
        if (status == kStatusClosed) invalidTransition();
        const auto closureReasonCvId = asStringOr(body, "closureReasonId", asStringOr(body, "closureReasonCvId"));
        if (closureReasonCvId.empty())
            throw ApiError(drogon::k400BadRequest, "closureReasonId is required",
                           "error.msg.group.closurereason.required");
        if (!isCenter) {
            auto members = co_await Mapper<m::GroupClient>(txn).findBy(Criteria(m::GroupClient::Cols::_group_id, id));
            if (!members.empty())
                throw ApiError(drogon::k409Conflict, "Cannot close a group that still has client members",
                               "error.msg.group.close.has.members");
        } else {
            auto children = co_await Mapper<m::Group>(txn).findBy(Criteria(m::Group::Cols::_parent_id, id));
            if (!children.empty())
                throw ApiError(drogon::k409Conflict, "Cannot close a center that still has associated groups",
                               "error.msg.center.close.has.groups");
        }
        row.setStatusEnum(kStatusClosed);
        row.setClosedonDate(dateOr(asStringOr(body, "closureDate"), Date::now()));
        row.setClosedonUserid(userIdOr(ctx));
        row.setClosureReasonCvId(closureReasonCvId);
    } else if (command == "assignStaff") {
        requirePermission(ctx, "ASSIGNSTAFF_" + label);
        const auto staffId = asStringOr(body, "staffId");
        if (staffId.empty())
            throw ApiError(drogon::k400BadRequest, "staffId is required", "error.msg.group.staffid.required");
        row.setStaffId(staffId);
    } else if (command == "unassignStaff") {
        requirePermission(ctx, "ASSIGNSTAFF_" + label);
        row.setStaffId(kZeroUuid);
    } else {
        throw ApiError(drogon::k400BadRequest, "Unknown command: " + command,
                       isCenter ? "error.msg.center.unknown.command" : "error.msg.group.unknown.command");
    }

    co_await mapper.update(row);
    co_await turbo::outbox::writeEvent(txn, ctx, isCenter ? "center" : "group", id, eventType, body);
    co_return co_await entityToJson(txn, id, isCenter);
}

