Task<HttpResponsePtr> SmsCampaignsController::command(HttpRequestPtr req, std::string id) {
    auto ctx = turbo::RequestContext::from(req);
    if (!ctx) co_return ApiResponse::httpUnauthorized("Missing trusted context");
    auto body = req->getJsonObject();
    Json::Value payload = body ? *body : Json::Value(Json::objectValue);
    // Fineract convention: the command can also arrive as a "?command=" query
    // parameter (e.g. POST /smscampaigns/{id}?command=activate).
    if (!payload.isMember("command") && !req->getParameter("command").empty())
        payload["command"] = req->getParameter("command");
    try {
        co_return ApiResponse::httpOk(co_await svc().smsCampaignCommand(*ctx, id, payload),
                                      "SMS campaign command executed");
    } catch (const ApiError &e) {
        co_return ApiResponse::httpError(e.status(), e.what(), e.globalisationCode());
    } catch (const std::exception &e) {
        co_return ApiResponse::httpError(k500InternalServerError, e.what());
    }
}
