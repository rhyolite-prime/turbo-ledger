drogon::Task<Json::Value> NotificationService::listSms(const turbo::RequestContext &ctx,
                                                        const std::string &status, int offset, int limit) {
    requirePermission(ctx, "READ_SMS");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    Mapper<m::SmsMessage> mapper(txn);

    auto rows = status.empty() ? co_await mapper.orderBy(m::SmsMessage::Cols::_created_at, SortOrder::DESC)
                                      .limit(limit)
                                      .offset(offset)
                                      .findAll()
                                : co_await mapper.orderBy(m::SmsMessage::Cols::_created_at, SortOrder::DESC)
                                      .limit(limit)
                                      .offset(offset)
                                      .findBy(Criteria(m::SmsMessage::Cols::_status, status));
    const auto total = status.empty() ? co_await mapper.count() : co_await mapper.count(Criteria(m::SmsMessage::Cols::_status, status));
    Json::Value items(Json::arrayValue);
    for (const auto &r : rows) items.append(smsMessageToJson(r));
    co_return turbo::pagedResult(static_cast<std::int64_t>(total), items);
}

drogon::Task<Json::Value> NotificationService::createSms(const turbo::RequestContext &ctx, Json::Value body) {
    requirePermission(ctx, "CREATE_SMS");
    const std::string mobileNo = asStringOr(body, "mobileNo");
    const std::string message = asStringOr(body, "message");
    if (mobileNo.empty() || message.empty())
        throw ApiError(drogon::k400BadRequest, "mobileNo and message are required",
                       "error.msg.sms.required.fields.missing");

    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    m::SmsMessage row;
    row.setMobileNo(mobileNo);
    row.setMessage(message);
    row.setStatus("PENDING");
    if (body.isMember("clientId")) row.setClientId(asStringOr(body, "clientId"));
    if (body.isMember("groupId")) row.setGroupId(asStringOr(body, "groupId"));
    if (body.isMember("staffId")) row.setStaffId(asStringOr(body, "staffId"));
    if (body.isMember("campaignId")) row.setCampaignId(asStringOr(body, "campaignId"));

    auto inserted = co_await Mapper<m::SmsMessage>(txn).insert(row);
    co_await turbo::outbox::writeEvent(txn, ctx, "sms", inserted.getValueOfId(), "sms.queued",
                                       smsMessageToJson(inserted));
    co_return smsMessageToJson(inserted);
}

