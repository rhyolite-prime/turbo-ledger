drogon::Task<Json::Value> NotificationService::listNotifications(const turbo::RequestContext &ctx,
                                                                  bool onlyUnread, int offset, int limit) {
    requirePermission(ctx, "READ_NOTIFICATION");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    Mapper<m::Notification> mapper(txn);

    Criteria crit(m::Notification::Cols::_user_id, ctx.userId);
    if (onlyUnread) crit = crit && Criteria(m::Notification::Cols::_is_read, CompareOperator::EQ, false);

    const auto total = co_await mapper.count(crit);
    auto rows = co_await mapper.orderBy(m::Notification::Cols::_created_at, SortOrder::DESC)
                    .limit(limit)
                    .offset(offset)
                    .findBy(crit);
    Json::Value items(Json::arrayValue);
    for (const auto &r : rows) items.append(notificationToJson(r));
    co_return turbo::pagedResult(static_cast<std::int64_t>(total), items);
}

drogon::Task<Json::Value> NotificationService::markNotificationsRead(const turbo::RequestContext &ctx,
                                                                      Json::Value body) {
    requirePermission(ctx, "UPDATE_NOTIFICATION");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    Mapper<m::Notification> mapper(txn);

    int updated = 0;
    if (asBoolOr(body, "all", false)) {
        auto rows = co_await mapper.findBy(Criteria(m::Notification::Cols::_user_id, ctx.userId) &&
                                           Criteria(m::Notification::Cols::_is_read, CompareOperator::EQ, false));
        for (auto &r : rows) {
            r.setIsRead(true);
            co_await mapper.update(r);
            ++updated;
        }
    } else if (body.isMember("notificationIds") && body["notificationIds"].isArray()) {
        for (const auto &idVal : body["notificationIds"]) {
            const std::string id = idVal.asString();
            auto rows = co_await mapper.findBy(Criteria(m::Notification::Cols::_id, id) &&
                                               Criteria(m::Notification::Cols::_user_id, ctx.userId));
            if (rows.empty()) continue;
            auto row = rows.front();
            row.setIsRead(true);
            co_await mapper.update(row);
            ++updated;
        }
    } else {
        throw ApiError(drogon::k400BadRequest, "Provide either {\"all\":true} or {\"notificationIds\":[...]}",
                       "error.msg.notification.required.fields.missing");
    }

    Json::Value result;
    result["updated"] = updated;
    co_return result;
}

