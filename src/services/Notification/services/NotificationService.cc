drogon::Task<Json::Value> NotificationService::smsCampaignCommand(const turbo::RequestContext &ctx,
                                                                   std::string id, Json::Value body) {
    requirePermission(ctx, "EXECUTE_SMSCAMPAIGN");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    auto row = co_await loadByPk<m::SmsCampaign>(txn, id, "smscampaign");

    const std::string command = asStringOr(body, "command");
    std::string newStatus;
    std::string eventType;
    if (command == "activate") {
        newStatus = "ACTIVE";
        eventType = "smscampaign.activated";
    } else if (command == "close" || command == "deactivate") {
        newStatus = "CLOSED";
        eventType = "smscampaign.closed";
    } else if (command == "reactivate") {
        newStatus = "PENDING";
        eventType = "smscampaign.reactivated";
    } else {
        throw ApiError(drogon::k400BadRequest, "Unknown command: " + command,
                       "error.msg.smscampaign.command.unknown");
    }

    row.setStatus(newStatus);
    co_await Mapper<m::SmsCampaign>(txn).update(row);
    co_await turbo::outbox::writeEvent(txn, ctx, "smscampaign", id, eventType, smsCampaignToJson(row));
    co_return smsCampaignToJson(row);
}

