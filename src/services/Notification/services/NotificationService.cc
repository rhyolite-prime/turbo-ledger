std::string asStringOr(const Json::Value &v, const char *key, const std::string &fallback = "") {
    return v.isMember(key) && !v[key].isNull() ? v[key].asString() : fallback;
}

bool asBoolOr(const Json::Value &v, const char *key, bool fallback) {
    return v.isMember(key) && v[key].isBool() ? v[key].asBool() : fallback;
}

int asIntOr(const Json::Value &v, const char *key, int fallback) {
    return v.isMember(key) && v[key].isInt() ? v[key].asInt() : fallback;
}

std::string writeJsonCompact(const Json::Value &v) {
    Json::StreamWriterBuilder w;
    w["indentation"] = "";
    return Json::writeString(w, v);
}

Json::Value parseJsonOr(const std::string &text, const Json::Value &fallback) {
    if (text.empty()) return fallback;
    Json::Value parsed;
    Json::CharReaderBuilder rb;
    std::string errs;
    std::istringstream iss(text);
    if (Json::parseFromStream(rb, iss, &parsed, &errs)) return parsed;
    return fallback;
}

/// Minimal "{{key}}" substitution renderer (see header-level scope note: no
/// mustache library is vendored and no inter-service data lookup exists).
std::string renderTemplate(const std::string &text, const Json::Value &values) {
    static const std::regex pattern(R"(\{\{\s*([A-Za-z0-9_]+)\s*\}\})");
    std::string result;
    result.reserve(text.size());
    std::size_t lastPos = 0;
    for (auto it = std::sregex_iterator(text.begin(), text.end(), pattern);
        it != std::sregex_iterator(); ++it) {
        const auto &match = *it;
        result.append(text, lastPos, static_cast<std::size_t>(match.position()) - lastPos);
        const std::string key = match[1].str();
        std::string replacement = match.str();
        if (values.isObject() && values.isMember(key) && !values[key].isNull()) {
            replacement = values[key].isString() ? values[key].asString() : writeJsonCompact(values[key]);
        }
        result.append(replacement);
        lastPos = static_cast<std::size_t>(match.position() + match.length());
    }
    result.append(text, lastPos, std::string::npos);
    return result;
}

std::string dateTimeStr(const Date &d) { return d.toDbStringLocal(); }

/// Accepts either a full "YYYY-MM-DD HH:MM:SS" timestamp or a bare
/// "YYYY-MM-DD" date (defaulted to midnight), matching the precedent set by
/// DepositAccountManagementService's date-string parsing.
Date parseDateTime(const std::string &text) {
    return Date::fromDbStringLocal(text.size() == 10 ? text + " 00:00:00" : text);
}

