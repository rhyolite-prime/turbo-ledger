drogon::Task<Json::Value> NotificationService::emailCampaignCommand(const turbo::RequestContext &ctx,
                                                                     std::string id, Json::Value body) {
    requirePermission(ctx, "EXECUTE_EMAILCAMPAIGN");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    auto row = co_await loadByPk<m::EmailCampaign>(txn, id, "emailcampaign");

    const std::string command = asStringOr(body, "command", "activate");
    std::string newStatus;
    std::string eventType;
    if (command == "activate") {
        newStatus = "ACTIVE";
        eventType = "emailcampaign.activated";
    } else if (command == "close" || command == "deactivate") {
        newStatus = "CLOSED";
        eventType = "emailcampaign.closed";
    } else if (command == "reactivate") {
        newStatus = "PENDING";
        eventType = "emailcampaign.reactivated";
    } else {
        throw ApiError(drogon::k400BadRequest, "Unknown command: " + command,
                       "error.msg.emailcampaign.command.unknown");
    }

    row.setStatus(newStatus);
    co_await Mapper<m::EmailCampaign>(txn).update(row);
    co_await turbo::outbox::writeEvent(txn, ctx, "emailcampaign", id, eventType, emailCampaignToJson(row));
    co_return emailCampaignToJson(row);
}

