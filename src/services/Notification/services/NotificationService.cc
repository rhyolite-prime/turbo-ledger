template <typename Model>
drogon::Task<Model> loadByPk(std::shared_ptr<drogon::orm::Transaction> txn, const std::string &id,
                             const std::string &what) {
    try {
        co_return co_await Mapper<Model>(txn).findByPrimaryKey(id);
    } catch (const UnexpectedRows &) {
        throw ApiError(drogon::k404NotFound, what + " not found",
                       "error.msg." + what + ".id.invalid");
    }
}

