#include "TemplatesController.h"

#include "services/TemplateService.h"
#include "turbo/ApiResponse.h"
#include "turbo/RequestContext.h"

using turbo::ApiResponse;
using turbo_ledger_template::ApiError;
using turbo_ledger_template::TemplateService;

namespace {
TemplateService &svc() {
    static TemplateService instance;
    return instance;
}
}  // namespace

Task<HttpResponsePtr> TemplatesController::creationTemplate(HttpRequestPtr req) {
    auto ctx = turbo::RequestContext::from(req);
    if (!ctx) co_return ApiResponse::httpUnauthorized("Missing trusted context");
    try {
        co_return ApiResponse::httpOk(co_await svc().creationTemplate(*ctx));
    } catch (const ApiError &e) {
        co_return ApiResponse::httpError(e.status(), e.what(), e.globalisationCode());
    } catch (const std::exception &e) {
        co_return ApiResponse::httpError(k500InternalServerError, e.what());
    }
}

