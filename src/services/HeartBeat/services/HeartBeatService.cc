drogon::Task<Json::Value> applyJobUpdate(std::shared_ptr<drogon::orm::Transaction> txn,
                                         const turbo::RequestContext &ctx, m::Job row,
                                         const Json::Value &body) {
    if (body.isMember("displayName")) row.setDisplayName(asStringOr(body, "displayName"));
    if (body.isMember("description")) row.setDescription(asStringOr(body, "description"));
    if (body.isMember("cronExpression")) row.setCronExpression(asStringOr(body, "cronExpression"));
    if (body.isMember("active")) row.setIsActive(asBoolOr(body, "active", row.getValueOfIsActive()));
    if (body.isMember("misfired"))
        row.setIsMisfired(asBoolOr(body, "misfired", row.getValueOfIsMisfired()));
    row.setUpdatedAt(Date::now());
    co_await Mapper<m::Job>(txn).update(row);
    co_await turbo::outbox::writeEvent(txn, ctx, "job", row.getValueOfId(), "job.updated", body);
    co_return jobToJson(row);
}
