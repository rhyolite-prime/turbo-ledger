drogon::Task<Json::Value> HeartBeatService::updateSteps(const turbo::RequestContext &ctx,
                                                        const std::string &jobName,
                                                        const Json::Value &body) {
    requirePermission(ctx, "UPDATE_JOB");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    auto job = co_await loadJobByShortName(txn, jobName);

    if (!body.isMember("steps") || !body["steps"].isArray())
        throw ApiError(drogon::k400BadRequest, "steps (array) is required",
                       "error.msg.job.steps.required");

    for (const auto &stepUpdate : body["steps"]) {
        const auto stepName = asStringOr(stepUpdate, "stepName");
        if (stepName.empty()) continue;
        auto rows = co_await Mapper<m::JobBusinessStep>(txn).findBy(
            Criteria(m::JobBusinessStep::Cols::_job_id, job.getValueOfId()) &&
            Criteria(m::JobBusinessStep::Cols::_step_name, stepName));
        if (rows.empty()) continue;
        auto step = rows.front();
        if (stepUpdate.isMember("stepOrder")) step.setStepOrder(asIntOr(stepUpdate, "stepOrder", step.getValueOfStepOrder()));
        if (stepUpdate.isMember("enabled"))
            step.setIsEnabled(asBoolOr(stepUpdate, "enabled", step.getValueOfIsEnabled()));
        step.setUpdatedAt(Date::now());
        co_await Mapper<m::JobBusinessStep>(txn).update(step);
    }

    co_await turbo::outbox::writeEvent(txn, ctx, "job", job.getValueOfId(), "job.steps.updated", body);
    co_return co_await stepsFor(txn, job);
}

