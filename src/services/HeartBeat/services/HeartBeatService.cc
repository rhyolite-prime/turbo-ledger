std::string asStringOr(const Json::Value &v, const char *key, const std::string &fallback = "") {
    return v.isMember(key) && !v[key].isNull() ? v[key].asString() : fallback;
}

bool asBoolOr(const Json::Value &v, const char *key, bool fallback) {
    return v.isMember(key) && v[key].isBool() ? v[key].asBool() : fallback;
}

int asIntOr(const Json::Value &v, const char *key, int fallback) {
    return v.isMember(key) && v[key].isInt() ? v[key].asInt() : fallback;
}

std::string dateTimeStr(const Date &d) { return d.toDbStringLocal(); }

Json::Value jobToJson(const m::Job &row) {
    Json::Value j;
    j["id"] = row.getValueOfId();
    j["shortName"] = row.getValueOfShortName();
    j["displayName"] = row.getValueOfDisplayName();
    j["description"] = row.getDescription() ? row.getValueOfDescription() : Json::Value();
    j["cronExpression"] = row.getCronExpression() ? row.getValueOfCronExpression() : Json::Value();
    j["active"] = row.getValueOfIsActive();
    j["misfired"] = row.getValueOfIsMisfired();
    j["createdAt"] = dateTimeStr(row.getValueOfCreatedAt());
    j["updatedAt"] = dateTimeStr(row.getValueOfUpdatedAt());
    return j;
}

Json::Value runHistoryToJson(const m::JobRunHistory &row) {
    Json::Value j;
    j["id"] = row.getValueOfId();
    j["jobId"] = row.getValueOfJobId();
    j["version"] = static_cast<Json::Int64>(row.getValueOfVersion());
    j["startTime"] = dateTimeStr(row.getValueOfStartTime());
    j["endTime"] = row.getEndTime() ? Json::Value(dateTimeStr(row.getValueOfEndTime())) : Json::Value();
    j["status"] = row.getValueOfStatus();
    j["triggerType"] = row.getValueOfTriggerType();
    j["errorLog"] = row.getErrorLog() ? row.getValueOfErrorLog() : Json::Value();
    return j;
}

Json::Value stepToJson(const m::JobBusinessStep &row) {
    Json::Value j;
    j["id"] = row.getValueOfId();
    j["jobId"] = row.getValueOfJobId();
    j["stepName"] = row.getValueOfStepName();
    j["stepOrder"] = row.getValueOfStepOrder();
    j["enabled"] = row.getValueOfIsEnabled();
    return j;
}

Json::Value schedulerStateToJson(const m::SchedulerState &row) {
    Json::Value j;
    j["active"] = row.getValueOfIsActive();
    j["updatedAt"] = dateTimeStr(row.getValueOfUpdatedAt());
    return j;
}

drogon::Task<m::Job> loadJobByShortName(std::shared_ptr<drogon::orm::Transaction> txn,
                                        const std::string &shortName) {
    auto rows =
        co_await Mapper<m::Job>(txn).findBy(Criteria(m::Job::Cols::_short_name, shortName));
    if (rows.empty())
        throw ApiError(drogon::k404NotFound, "Job not found: " + shortName, "error.msg.job.id.invalid");
    co_return rows.front();
}

drogon::Task<m::Job> loadJobById(std::shared_ptr<drogon::orm::Transaction> txn, const std::string &id) {
    try {
        co_return co_await Mapper<m::Job>(txn).findByPrimaryKey(id);
    } catch (const UnexpectedRows &) {
        throw ApiError(drogon::k404NotFound, "Job not found", "error.msg.job.id.invalid");
    }
}

/// Records an honest no-op run (see class-level scope note in the header):
/// no cross-service execution happens, but every attempt is durably logged.
drogon::Task<Json::Value> recordRun(std::shared_ptr<drogon::orm::Transaction> txn,
                                    const turbo::RequestContext &ctx, const m::Job &job,
                                    const std::string &triggerType) {
    const auto countRows = co_await Mapper<m::JobRunHistory>(txn).count(
        Criteria(m::JobRunHistory::Cols::_job_id, job.getValueOfId()));

    const auto now = Date::now();
    m::JobRunHistory history;
    history.setJobId(job.getValueOfId());
    history.setVersion(static_cast<int64_t>(countRows) + 1);
    history.setStartTime(now);
    history.setEndTime(now);
    history.setStatus("COMPLETED");
    history.setTriggerType(triggerType);
    history.setErrorLog(
        "No-op: job execution engine not implemented in this sandbox (no inter-service RPC "
        "client exists to call the owning service's real business logic). This run was "
        "recorded for audit purposes only.");

    history = co_await Mapper<m::JobRunHistory>(txn).insert(history);
    co_await turbo::outbox::writeEvent(txn, ctx, "job", job.getValueOfId(), "job.run.recorded",
                                       runHistoryToJson(history));
    co_return runHistoryToJson(history);
}

drogon::Task<Json::Value> runHistoryPage(std::shared_ptr<drogon::orm::Transaction> txn,
                                         const std::string &jobId, int offset, int limit) {
    Mapper<m::JobRunHistory> mapper(txn);
    Criteria crit(m::JobRunHistory::Cols::_job_id, jobId);
    const auto total = co_await mapper.count(crit);
    auto rows = co_await mapper.orderBy(m::JobRunHistory::Cols::_start_time, SortOrder::DESC)
                    .limit(limit)
                    .offset(offset)
                    .findBy(crit);
    Json::Value items(Json::arrayValue);
    for (const auto &r : rows) items.append(runHistoryToJson(r));
    co_return turbo::pagedResult(static_cast<std::int64_t>(total), items);
}

drogon::Task<Json::Value> stepsFor(std::shared_ptr<drogon::orm::Transaction> txn, const m::Job &job) {
    auto rows = co_await Mapper<m::JobBusinessStep>(txn)
                    .orderBy(m::JobBusinessStep::Cols::_step_order)
                    .findBy(Criteria(m::JobBusinessStep::Cols::_job_id, job.getValueOfId()));
    Json::Value items(Json::arrayValue);
    for (const auto &r : rows) items.append(stepToJson(r));
    co_return items;
}

