drogon::Task<Json::Value> TellerService::createTeller(const turbo::RequestContext &ctx,
                                                       const Json::Value &body) {
    requirePermission(ctx, "CREATE_TELLER");
    const auto officeId = asStringOr(body, "officeId");
    if (officeId.empty())
        throw ApiError(drogon::k400BadRequest, "officeId is required", "error.msg.teller.officeid.required");
    const auto name = asStringOr(body, "name");
    if (name.empty())
        throw ApiError(drogon::k400BadRequest, "name is required", "error.msg.teller.name.required");
    const auto startDateStr = asStringOr(body, "startDate");
    if (startDateStr.empty())
        throw ApiError(drogon::k400BadRequest, "startDate is required",
                       "error.msg.teller.startdate.required");

    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    m::Teller row;
    row.setOfficeId(officeId);
    row.setName(name);
    const auto description = asStringOr(body, "description");
    if (!description.empty()) row.setDescription(description);
    row.setStatusEnum(asIntOr(body, "status", kStatusActive));
    row.setStartDate(dateOr(startDateStr, Date::now()));
    const auto endDateStr = asStringOr(body, "endDate");
    if (!endDateStr.empty()) row.setEndDate(dateOr(endDateStr, Date::now()));

    try {
        row = co_await Mapper<m::Teller>(txn).insert(row);
    } catch (const DrogonDbException &e) {
        throw ApiError(drogon::k400BadRequest, std::string("Could not create teller: ") + e.base().what(),
                       "error.msg.teller.create.failed");
    }
    co_await turbo::outbox::writeEvent(txn, ctx, "teller", row.getValueOfId(), "teller.created", body);
    co_return tellerToJson(row);
}

drogon::Task<Json::Value> TellerService::updateTeller(const turbo::RequestContext &ctx, const std::string &id,
                                                       const Json::Value &body) {
    requirePermission(ctx, "UPDATE_TELLER");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    auto row = co_await loadTellerRow(txn, id);
    if (body.isMember("officeId")) row.setOfficeId(asStringOr(body, "officeId"));
    if (body.isMember("name")) row.setName(asStringOr(body, "name"));
    if (body.isMember("description")) row.setDescription(asStringOr(body, "description"));
    if (body.isMember("status")) row.setStatusEnum(asIntOr(body, "status", row.getValueOfStatusEnum()));
    if (body.isMember("startDate")) row.setStartDate(dateOr(asStringOr(body, "startDate"), Date::now()));
    if (body.isMember("endDate")) {
        const auto endDateStr = asStringOr(body, "endDate");
        if (endDateStr.empty())
            row.setEndDateToNull();
        else
            row.setEndDate(dateOr(endDateStr, Date::now()));
    }
    try {
        co_await Mapper<m::Teller>(txn).update(row);
    } catch (const DrogonDbException &e) {
        throw ApiError(drogon::k400BadRequest, std::string("Could not update teller: ") + e.base().what(),
                       "error.msg.teller.update.failed");
    }
    co_await turbo::outbox::writeEvent(txn, ctx, "teller", id, "teller.updated", body);
    co_return tellerToJson(row);
}

drogon::Task<void> TellerService::deleteTeller(const turbo::RequestContext &ctx, const std::string &id) {
    requirePermission(ctx, "DELETE_TELLER");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    auto row = co_await loadTellerRow(txn, id);
    auto cashierIds = co_await cashierIdsForTeller(txn, id);
    if (!cashierIds.empty())
        throw ApiError(drogon::k409Conflict, "Cannot delete a teller that still has cashiers assigned",
                       "error.msg.teller.cannot.delete.has.cashiers");
    co_await Mapper<m::Teller>(txn).deleteOne(row);
    co_await turbo::outbox::writeEvent(txn, ctx, "teller", id, "teller.deleted", Json::Value());
}

