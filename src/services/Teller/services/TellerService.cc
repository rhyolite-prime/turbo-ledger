constexpr const char *kZeroUuid = "00000000-0000-0000-0000-000000000000";

// tellers.status_enum — matches the real Fineract sample createTeller
// request body ({"status":300, ...}) and the column's own `DEFAULT 300`.
constexpr int kStatusActive = 300;
constexpr int kStatusInactive = 400;

// cashier_transactions.txn_type — Fineract's own fixed codes.
constexpr int kTxnAllocate = 101;
constexpr int kTxnSettle = 102;

std::string statusLabel(int status) {
    switch (status) {
        case kStatusActive: return "active";
        case kStatusInactive: return "inactive";
        default: return "unknown";
    }
}

std::string txnTypeLabel(int txnType) {
    switch (txnType) {
        case kTxnAllocate: return "Allocate Cash";
        case kTxnSettle: return "Settle Cash";
        default: return "Unknown";
    }
}

bool isSet(const std::string &uuid) { return !uuid.empty() && uuid != kZeroUuid; }

Date dateOr(const std::string &text, const Date &fallback) {
    if (text.empty()) return fallback;
    return Date::fromDbStringLocal(text);
}
std::string dateStr(const Date &d) { return d.toDbStringLocal().substr(0, 10); }

std::string asStringOr(const Json::Value &v, const char *key, const std::string &fallback = "") {
    return v.isMember(key) && !v[key].isNull() ? v[key].asString() : fallback;
}
int asIntOr(const Json::Value &v, const char *key, int fallback) {
    return v.isMember(key) && v[key].isInt() ? v[key].asInt() : fallback;
}
bool asBoolOr(const Json::Value &v, const char *key, bool fallback) {
    return v.isMember(key) && v[key].isBool() ? v[key].asBool() : fallback;
}
std::string userIdOr(const turbo::RequestContext &ctx) {
    return ctx.userId.empty() ? kZeroUuid : ctx.userId;
}

Json::Value tellerToJson(const m::Teller &row) {
    Json::Value j;
    j["id"] = row.getValueOfId();
    j["officeId"] = row.getValueOfOfficeId();
    j["name"] = row.getValueOfName();
    if (row.getDescription() && !row.getValueOfDescription().empty())
        j["description"] = row.getValueOfDescription();
    j["status"] = row.getValueOfStatusEnum();
    j["statusName"] = statusLabel(row.getValueOfStatusEnum());
    j["startDate"] = dateStr(row.getValueOfStartDate());
    if (row.getEndDate()) j["endDate"] = dateStr(row.getValueOfEndDate());
    return j;
}

Json::Value cashierToJson(const m::Cashier &row) {
    Json::Value j;
    j["id"] = row.getValueOfId();
    j["tellerId"] = row.getValueOfTellerId();
    j["staffId"] = row.getValueOfStaffId();
    if (row.getDescription() && !row.getValueOfDescription().empty())
        j["description"] = row.getValueOfDescription();
    j["startDate"] = dateStr(row.getValueOfStartDate());
    if (row.getEndDate()) j["endDate"] = dateStr(row.getValueOfEndDate());
    j["isFullDay"] = row.getValueOfIsFullDay();
    if (row.getStartTime() && !row.getValueOfStartTime().empty()) j["startTime"] = row.getValueOfStartTime();
    if (row.getEndTime() && !row.getValueOfEndTime().empty()) j["endTime"] = row.getValueOfEndTime();
    return j;
}

Json::Value transactionToJson(const m::CashierTransaction &row) {
    Json::Value j;
    j["id"] = row.getValueOfId();
    j["cashierId"] = row.getValueOfCashierId();
    Json::Value txnType;
    txnType["id"] = row.getValueOfTxnType();
    txnType["value"] = txnTypeLabel(row.getValueOfTxnType());
    j["txnType"] = txnType;
    auto parsedAmount = turbo::Money::parse(row.getValueOfTxnAmount());
    j["txnAmount"] = parsedAmount ? parsedAmount->toString(false) : row.getValueOfTxnAmount();
    j["txnDate"] = dateStr(row.getValueOfTxnDate());
    j["currencyCode"] = row.getValueOfCurrencyCode();
    if (row.getEntityId() && isSet(row.getValueOfEntityId())) j["entityId"] = row.getValueOfEntityId();
    if (row.getEntityType() && !row.getValueOfEntityType().empty())
        j["entityType"] = row.getValueOfEntityType();
    if (row.getTxnNote() && !row.getValueOfTxnNote().empty()) j["txnNote"] = row.getValueOfTxnNote();
    return j;
}

