drogon::Task<Json::Value> TellerService::createCashier(const turbo::RequestContext &ctx,
                                                       const std::string &tellerId, const Json::Value &body) {
    requirePermission(ctx, "CREATE_CASHIER");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    co_await loadTellerRow(txn, tellerId);

    const auto staffId = asStringOr(body, "staffId");
    if (staffId.empty())
        throw ApiError(drogon::k400BadRequest, "staffId is required", "error.msg.cashier.staffid.required");
    const auto startDateStr = asStringOr(body, "startDate");
    if (startDateStr.empty())
        throw ApiError(drogon::k400BadRequest, "startDate is required",
                       "error.msg.cashier.startdate.required");
    const bool isFullDay = asBoolOr(body, "isFullDay", true);
    const auto startTime = asStringOr(body, "startTime");
    const auto endTime = asStringOr(body, "endTime");
    if (!isFullDay && (startTime.empty() || endTime.empty()))
        throw ApiError(drogon::k400BadRequest,
                       "startTime and endTime are required when isFullDay is false",
                       "error.msg.cashier.time.window.required");

    m::Cashier row;
    row.setTellerId(tellerId);
    row.setStaffId(staffId);
    const auto description = asStringOr(body, "description");
    if (!description.empty()) row.setDescription(description);
    row.setStartDate(dateOr(startDateStr, Date::now()));
    const auto endDateStr = asStringOr(body, "endDate");
    if (!endDateStr.empty()) row.setEndDate(dateOr(endDateStr, Date::now()));
    row.setIsFullDay(isFullDay);
    if (!isFullDay) {
        row.setStartTime(startTime);
        row.setEndTime(endTime);
    }

    row = co_await Mapper<m::Cashier>(txn).insert(row);
    co_await turbo::outbox::writeEvent(txn, ctx, "cashier", row.getValueOfId(), "cashier.created", body);
    co_return cashierToJson(row);
}

