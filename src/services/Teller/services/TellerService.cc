drogon::Task<Json::Value> TellerService::listCashiersGlobal(const turbo::RequestContext &ctx,
                                                            const std::string &officeId,
                                                            const std::string &staffId,
                                                            const std::string &tellerId,
                                                            const std::string &date, int offset, int limit) {
    requirePermission(ctx, "READ_CASHIER");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);

    Criteria crit;
    bool any = false;
    auto addAnd = [&](const Criteria &c) {
        crit = any ? (crit && c) : c;
        any = true;
    };

    if (!tellerId.empty()) {
        addAnd(Criteria(m::Cashier::Cols::_teller_id, tellerId));
    } else if (!officeId.empty()) {
        auto tellers = co_await Mapper<m::Teller>(txn).findBy(Criteria(m::Teller::Cols::_office_id, officeId));
        if (tellers.empty()) co_return turbo::pagedResult(0, Json::Value(Json::arrayValue));
        Criteria tellerCrit = Criteria(m::Cashier::Cols::_teller_id, tellers.front().getValueOfId());
        for (size_t i = 1; i < tellers.size(); ++i)
            tellerCrit = tellerCrit || Criteria(m::Cashier::Cols::_teller_id, tellers[i].getValueOfId());
        addAnd(tellerCrit);
    }
    if (!staffId.empty()) addAnd(Criteria(m::Cashier::Cols::_staff_id, staffId));

    Mapper<m::Cashier> mapper(txn);
    // `date` (is this cashier rostered to be on duty on this date?) needs an
    // "end_date IS NULL OR end_date >= date" check; rather than depend on an
    // unverified IsNull Criteria overload with no other precedent in this
    // codebase, filter that condition in C++ after fetching every
    // office/staff/teller-matching row (cashier rosters per office are a
    // small set in practice) instead of pushing it into SQL.
    auto rows = any ? co_await mapper.orderBy(m::Cashier::Cols::_start_date, SortOrder::DESC).findBy(crit)
                     : co_await mapper.orderBy(m::Cashier::Cols::_start_date, SortOrder::DESC).findAll();
    std::vector<m::Cashier> filtered;
    if (date.empty()) {
        filtered = std::move(rows);
    } else {
        const auto onDate = dateOr(date, Date::now());
        for (auto &r : rows) {
            if (r.getValueOfStartDate().microSecondsSinceEpoch() > onDate.microSecondsSinceEpoch()) continue;
            if (r.getEndDate() &&
                r.getValueOfEndDate().microSecondsSinceEpoch() < onDate.microSecondsSinceEpoch())
                continue;
            filtered.push_back(r);
        }
    }

    Json::Value items(Json::arrayValue);
    const std::int64_t total = static_cast<std::int64_t>(filtered.size());
    for (std::size_t i = static_cast<std::size_t>(offset); i < filtered.size() && items.size() < static_cast<Json::ArrayIndex>(limit); ++i)
        items.append(cashierToJson(filtered[i]));
    co_return turbo::pagedResult(total, items);
}

drogon::Task<Json::Value> TellerService::cashiersJournal(const turbo::RequestContext &ctx,
                                                         const std::string &cashierId,
                                                         const std::string &tellerId,
                                                         const std::string &currencyCode,
                                                         const std::string &fromDate, const std::string &toDate,
                                                         int offset, int limit) {
    requirePermission(ctx, "READ_CASHIERTRANSACTIONS");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);

    Criteria crit;
    bool any = false;
    auto addAnd = [&](const Criteria &c) {
        crit = any ? (crit && c) : c;
        any = true;
    };

    if (!cashierId.empty()) {
        addAnd(Criteria(m::CashierTransaction::Cols::_cashier_id, cashierId));
    } else if (!tellerId.empty()) {
        auto cashierIds = co_await cashierIdsForTeller(txn, tellerId);
        if (cashierIds.empty()) co_return turbo::pagedResult(0, Json::Value(Json::arrayValue));
        Criteria idCrit = Criteria(m::CashierTransaction::Cols::_cashier_id, cashierIds.front());
        for (size_t i = 1; i < cashierIds.size(); ++i)
            idCrit = idCrit || Criteria(m::CashierTransaction::Cols::_cashier_id, cashierIds[i]);
        addAnd(idCrit);
    }
    if (!currencyCode.empty()) addAnd(Criteria(m::CashierTransaction::Cols::_currency_code, currencyCode));
    if (!fromDate.empty())
        addAnd(Criteria(m::CashierTransaction::Cols::_txn_date, CompareOperator::GE, dateOr(fromDate, Date::now())));
    if (!toDate.empty())
        addAnd(Criteria(m::CashierTransaction::Cols::_txn_date, CompareOperator::LE, dateOr(toDate, Date::now())));

    Mapper<m::CashierTransaction> mapper(txn);
    const auto total = any ? co_await mapper.count(crit) : co_await mapper.count();
    auto rows = any ? co_await mapper.orderBy(m::CashierTransaction::Cols::_txn_date, SortOrder::DESC)
                           .limit(limit)
                           .offset(offset)
                           .findBy(crit)
                     : co_await mapper.orderBy(m::CashierTransaction::Cols::_txn_date, SortOrder::DESC)
                           .limit(limit)
                           .offset(offset)
                           .findAll();
    Json::Value items(Json::arrayValue);
    for (const auto &r : rows) items.append(transactionToJson(r));
    co_return turbo::pagedResult(static_cast<std::int64_t>(total), items);
}

