drogon::Task<Json::Value> TellerService::cashierSummaryAndTransactions(const turbo::RequestContext &ctx,
                                                                      const std::string &tellerId,
                                                                      const std::string &cashierId,
                                                                      const std::string &currencyCode,
                                                                      int offset, int limit) {
    requirePermission(ctx, "READ_CASHIERTRANSACTIONS");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    auto teller = co_await loadTellerRow(txn, tellerId);
    auto cashier = co_await loadCashierRow(txn, tellerId, cashierId);

    Criteria crit = Criteria(m::CashierTransaction::Cols::_cashier_id, cashierId);
    if (!currencyCode.empty()) crit = crit && Criteria(m::CashierTransaction::Cols::_currency_code, currencyCode);
    Mapper<m::CashierTransaction> mapper(txn);
    const auto total = co_await mapper.count(crit);
    auto rows = co_await mapper.orderBy(m::CashierTransaction::Cols::_txn_date, SortOrder::DESC)
                    .limit(limit)
                    .offset(offset)
                    .findBy(crit);

    turbo::Money sumAllocate, sumSettle;
    for (const auto &r : rows) {
        auto amt = turbo::Money::parse(r.getValueOfTxnAmount()).value_or(turbo::Money());
        if (r.getValueOfTxnType() == kTxnAllocate)
            sumAllocate += amt;
        else if (r.getValueOfTxnType() == kTxnSettle)
            sumSettle += amt;
    }

    Json::Value j;
    j["tellerId"] = tellerId;
    j["tellerName"] = teller.getValueOfName();
    j["cashierId"] = cashierId;
    j["cashierStaffId"] = cashier.getValueOfStaffId();
    j["sumCashAllocation"] = sumAllocate.toString(false);
    j["sumCashSettlement"] = sumSettle.toString(false);
    j["netCash"] = (sumAllocate - sumSettle).toString(false);
    Json::Value items(Json::arrayValue);
    for (const auto &r : rows) items.append(transactionToJson(r));
    j["cashierTransactions"] = turbo::pagedResult(static_cast<std::int64_t>(total), items);
    co_return j;
}

