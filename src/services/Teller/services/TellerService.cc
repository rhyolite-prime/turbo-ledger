drogon::Task<Json::Value> TellerService::tellerTransactions(const turbo::RequestContext &ctx,
                                                            const std::string &tellerId, int offset,
                                                            int limit) {
    requirePermission(ctx, "READ_CASHIERTRANSACTIONS");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    co_await loadTellerRow(txn, tellerId);
    auto cashierIds = co_await cashierIdsForTeller(txn, tellerId);
    if (cashierIds.empty()) co_return turbo::pagedResult(0, Json::Value(Json::arrayValue));

    Criteria crit = Criteria(m::CashierTransaction::Cols::_cashier_id, cashierIds.front());
    for (size_t i = 1; i < cashierIds.size(); ++i)
        crit = crit || Criteria(m::CashierTransaction::Cols::_cashier_id, cashierIds[i]);

    Mapper<m::CashierTransaction> mapper(txn);
    const auto total = co_await mapper.count(crit);
    auto rows = co_await mapper.orderBy(m::CashierTransaction::Cols::_txn_date, SortOrder::DESC)
                    .limit(limit)
                    .offset(offset)
                    .findBy(crit);
    Json::Value items(Json::arrayValue);
    for (const auto &r : rows) items.append(transactionToJson(r));
    co_return turbo::pagedResult(static_cast<std::int64_t>(total), items);
}

