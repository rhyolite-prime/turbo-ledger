drogon::Task<m::Teller> loadTellerRow(std::shared_ptr<drogon::orm::Transaction> txn, const std::string &id) {
    try {
        co_return co_await Mapper<m::Teller>(txn).findByPrimaryKey(id);
    } catch (const UnexpectedRows &) {
        throw ApiError(drogon::k404NotFound, "Teller not found", "error.msg.teller.id.invalid");
    }
}

drogon::Task<m::Cashier> loadCashierRow(std::shared_ptr<drogon::orm::Transaction> txn,
                                        const std::string &tellerId, const std::string &cashierId) {
    m::Cashier row;
    try {
        row = co_await Mapper<m::Cashier>(txn).findByPrimaryKey(cashierId);
    } catch (const UnexpectedRows &) {
        throw ApiError(drogon::k404NotFound, "Cashier not found", "error.msg.cashier.id.invalid");
    }
    if (row.getValueOfTellerId() != tellerId)
        throw ApiError(drogon::k404NotFound, "Cashier not found", "error.msg.cashier.id.invalid");
    co_return row;
}

/// Ids of every cashier rostered to `tellerId`. Used to build an OR-chain
/// Criteria for teller-level transaction/journal views -- CoroMapper has no
/// join support in this codebase (see every other service's precedent of
/// building WHERE col = $1 OR col = $2 ... chains instead of raw SQL joins).
drogon::Task<std::vector<std::string>> cashierIdsForTeller(std::shared_ptr<drogon::orm::Transaction> txn,
                                                           const std::string &tellerId) {
    auto rows = co_await Mapper<m::Cashier>(txn).findBy(Criteria(m::Cashier::Cols::_teller_id, tellerId));
    std::vector<std::string> ids;
    ids.reserve(rows.size());
    for (const auto &r : rows) ids.push_back(r.getValueOfId());
    co_return ids;
}

