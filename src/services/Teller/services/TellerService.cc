/// Shared implementation for allocate/settle -- same shape, differ only in
/// txn_type and (for settle) the balance guard.
drogon::Task<Json::Value> postCashierTransaction(TellerService::Txn txn, const turbo::RequestContext &ctx,
                                                 const std::string &tellerId, const std::string &cashierId,
                                                 const Json::Value &body, int txnType) {
    auto cashier = co_await loadCashierRow(txn, tellerId, cashierId);
    const auto currencyCode = asStringOr(body, "currencyCode");
    if (currencyCode.empty())
        throw ApiError(drogon::k400BadRequest, "currencyCode is required",
                       "error.msg.cashiertransaction.currencycode.required");
    const auto amountStr = asStringOr(body, "txnAmount");
    auto amount = turbo::Money::parse(amountStr);
    if (!amount || !(*amount > turbo::Money()))
        throw ApiError(drogon::k400BadRequest, "txnAmount must be a positive decimal amount",
                       "error.msg.cashiertransaction.amount.invalid");

    if (txnType == kTxnSettle) {
        auto allocatedRows = co_await Mapper<m::CashierTransaction>(txn).findBy(
            Criteria(m::CashierTransaction::Cols::_cashier_id, cashierId) &&
            Criteria(m::CashierTransaction::Cols::_currency_code, currencyCode) &&
            Criteria(m::CashierTransaction::Cols::_txn_type, kTxnAllocate));
        auto settledRows = co_await Mapper<m::CashierTransaction>(txn).findBy(
            Criteria(m::CashierTransaction::Cols::_cashier_id, cashierId) &&
            Criteria(m::CashierTransaction::Cols::_currency_code, currencyCode) &&
            Criteria(m::CashierTransaction::Cols::_txn_type, kTxnSettle));
        turbo::Money net;
        for (const auto &r : allocatedRows)
            net += turbo::Money::parse(r.getValueOfTxnAmount()).value_or(turbo::Money());
        for (const auto &r : settledRows)
            net -= turbo::Money::parse(r.getValueOfTxnAmount()).value_or(turbo::Money());
        if (*amount > net)
            throw ApiError(drogon::k400BadRequest,
                           "Settlement amount exceeds the cashier's net allocated balance",
                           "error.msg.cashiertransaction.insufficient.balance");
    }

    m::CashierTransaction row;
    row.setCashierId(cashierId);
    row.setTxnType(txnType);
    row.setTxnAmount(amount->toString(false));
    row.setTxnDate(dateOr(asStringOr(body, "txnDate"), Date::now()));
    row.setCurrencyCode(currencyCode);
    const auto txnNote = asStringOr(body, "txnNote");
    if (!txnNote.empty()) row.setTxnNote(txnNote);

    row = co_await Mapper<m::CashierTransaction>(txn).insert(row);
    co_await turbo::outbox::writeEvent(
        txn, ctx, "cashier", cashierId, txnType == kTxnAllocate ? "cashier.cash.allocated" : "cashier.cash.settled",
        body);
    co_return transactionToJson(row);
}

