drogon::Task<Json::Value> TellerService::listTellers(const turbo::RequestContext &ctx,
                                                     const std::string &officeId, const std::string &status,
                                                     const std::string &nameLike, int offset, int limit) {
    requirePermission(ctx, "READ_TELLER");
    auto txn = co_await turbo::db::beginTenantTxn(db(), ctx);
    Mapper<m::Teller> mapper(txn);
    Criteria crit;
    bool any = false;
    auto addAnd = [&](const Criteria &c) {
        crit = any ? (crit && c) : c;
        any = true;
    };
    if (!officeId.empty()) addAnd(Criteria(m::Teller::Cols::_office_id, officeId));
    if (!status.empty()) {
        try {
            addAnd(Criteria(m::Teller::Cols::_status_enum, std::stoi(status)));
        } catch (...) {
        }
    }
    if (!nameLike.empty())
        addAnd(Criteria(m::Teller::Cols::_name, CompareOperator::Like, "%" + nameLike + "%"));

    const auto total = any ? co_await mapper.count(crit) : co_await mapper.count();
    auto rows = any ? co_await mapper.orderBy(m::Teller::Cols::_name)
                           .limit(limit)
                           .offset(offset)
                           .findBy(crit)
                     : co_await mapper.orderBy(m::Teller::Cols::_name).limit(limit).offset(offset).findAll();
    Json::Value items(Json::arrayValue);
    for (const auto &r : rows) items.append(tellerToJson(r));
    co_return turbo::pagedResult(static_cast<std::int64_t>(total), items);
}

